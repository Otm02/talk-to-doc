import { afterEach, describe, expect, it, vi } from "vitest";
import { stubYoutube } from "@test/youtubeFetch";
import type { TranscriptProviderName } from "@/lib/wire/ingest";
import { buildProviders, createChain } from "./index";
import {
  TranscriptError,
  type Transcript,
  type TranscriptErrorCode,
  type TranscriptProvider,
} from "./provider";

const ID = "jNQXAC9IVRw";
const signal = () => new AbortController().signal;

const transcript = (title: string): Transcript => ({
  title,
  channel: "",
  durationSec: 10,
  language: "en",
  isAutoGenerated: null,
  segments: [{ startMs: 0, durMs: 1000, text: "hello" }],
});

function fake(
  name: TranscriptProviderName,
  outcome: TranscriptErrorCode | Error | "ok",
): TranscriptProvider & { fetch: ReturnType<typeof vi.fn> } {
  return {
    name,
    fetch: vi.fn(async () => {
      if (outcome === "ok") return transcript(name);
      throw outcome instanceof Error ? outcome : new TranscriptError(outcome);
    }),
  };
}

afterEach(() => {
  vi.unstubAllGlobals();
  vi.useRealTimers();
});

describe("createChain", () => {
  it("returns the first provider's answer and does not call the second", async () => {
    const direct = fake("direct", "ok");
    const supadata = fake("supadata", "ok");
    const result = await createChain([direct, supadata]).fetch(
      ID,
      "en",
      signal(),
    );

    expect(result.provider).toBe("direct");
    expect(result.transcript.title).toBe("direct");
    expect(result.attempts).toEqual([]);
    expect(supadata.fetch).not.toHaveBeenCalled();
  });

  it.each(["BLOCKED", "UPSTREAM_TIMEOUT", "UPSTREAM_FAILED"] as const)(
    "falls through to the next provider on %s",
    async (code) => {
      const direct = fake("direct", code);
      const supadata = fake("supadata", "ok");
      const result = await createChain([direct, supadata]).fetch(
        ID,
        "en",
        signal(),
      );

      expect(result.provider).toBe("supadata");
      expect(result.attempts).toEqual([{ provider: "direct", code }]);
    },
  );

  it.each([
    "NO_CAPTIONS",
    "VIDEO_UNAVAILABLE",
    "AGE_RESTRICTED",
    "LIVE_NOT_SUPPORTED",
    "PROVIDER_QUOTA",
  ] as const)(
    "stops at %s: the next provider would say the same",
    async (code) => {
      const direct = fake("direct", code);
      const supadata = fake("supadata", "ok");
      await expect(
        createChain([direct, supadata]).fetch(ID, "en", signal()),
      ).rejects.toMatchObject({ code });
      expect(supadata.fetch).not.toHaveBeenCalled();
    },
  );

  it("shows the last error when every provider fails", async () => {
    const chain = createChain([
      fake("direct", "BLOCKED"),
      fake("supadata", "UPSTREAM_FAILED"),
    ]);
    await expect(chain.fetch(ID, "en", signal())).rejects.toMatchObject({
      code: "UPSTREAM_FAILED",
    });
  });

  it("reports a blocked direct fetch as blocked when it is the only provider", async () => {
    await expect(
      createChain([fake("direct", "BLOCKED")]).fetch(ID, "en", signal()),
    ).rejects.toMatchObject({ code: "BLOCKED" });
  });

  it("surfaces quota exhaustion from the fallback", async () => {
    const chain = createChain([
      fake("direct", "BLOCKED"),
      fake("supadata", "PROVIDER_QUOTA"),
    ]);
    await expect(chain.fetch(ID, "en", signal())).rejects.toMatchObject({
      code: "PROVIDER_QUOTA",
    });
  });

  it("treats an unexpected throw as a provider failure and moves on", async () => {
    const result = await createChain([
      fake("direct", new TypeError("boom")),
      fake("supadata", "ok"),
    ]).fetch(ID, "en", signal());
    expect(result.provider).toBe("supadata");
    expect(result.attempts).toEqual([
      { provider: "direct", code: "UPSTREAM_FAILED" },
    ]);
  });

  it("stops without trying the next provider when the caller aborted", async () => {
    const controller = new AbortController();
    const abort = new DOMException("client left", "AbortError");
    const direct: TranscriptProvider = {
      name: "direct",
      fetch: async () => {
        controller.abort(abort);
        throw abort;
      },
    };
    const supadata = fake("supadata", "ok");
    await expect(
      createChain([direct, supadata]).fetch(ID, "en", controller.signal),
    ).rejects.toBe(abort);
    expect(supadata.fetch).not.toHaveBeenCalled();
  });

  it("fails cleanly with no providers", async () => {
    await expect(
      createChain([]).fetch(ID, "en", signal()),
    ).rejects.toMatchObject({ code: "UPSTREAM_FAILED" });
  });

  it("passes the video, language and signal to each provider", async () => {
    const direct = fake("direct", "BLOCKED");
    const supadata = fake("supadata", "ok");
    const s = signal();
    await createChain([direct, supadata]).fetch(ID, "fr", s);
    expect(direct.fetch).toHaveBeenCalledWith(ID, "fr", s);
    expect(supadata.fetch).toHaveBeenCalledWith(ID, "fr", s);
  });
});

describe("buildProviders", () => {
  it("registers Supadata only when a key is set", () => {
    expect(
      buildProviders({ supadataApiKey: undefined, onVercel: false }).map(
        (p) => p.name,
      ),
    ).toEqual(["direct"]);
    expect(
      buildProviders({ supadataApiKey: "sd_x", onVercel: false }).map(
        (p) => p.name,
      ),
    ).toEqual(["direct", "supadata"]);
  });

  /**
   * YouTube never answers; Supadata does. Returns how many requests have
   * reached Supadata after `ms` of fake time, and the pending chain call.
   */
  async function runWithHangingYoutube(
    env: { supadataApiKey: string | undefined; onVercel: boolean },
    ms: number,
  ) {
    vi.useFakeTimers();
    const youtube = stubYoutube("manual", {
      watch: (_n, init) =>
        new Promise<Response>((_resolve, reject) => {
          init?.signal?.addEventListener("abort", () =>
            reject(init.signal?.reason),
          );
        }),
    });
    const supadataCalls: string[] = [];
    vi.stubGlobal("fetch", async (input: string | URL, init?: RequestInit) => {
      const url = new URL(input.toString());
      if (url.hostname === "api.supadata.ai") {
        supadataCalls.push(url.pathname);
        return Response.json({
          lang: "en",
          content: [{ text: "hi", offset: 0, duration: 1000 }],
        });
      }
      if (url.pathname === "/oembed") return new Response("", { status: 404 });
      return youtube.fetchMock(input, init);
    });

    const pending = createChain(buildProviders(env)).fetch(ID, "en", signal());
    const outcome = pending.then(
      (r) => r,
      (e: unknown) => e,
    );
    await vi.advanceTimersByTimeAsync(ms);
    return { supadataCalls, outcome };
  }

  it("on Vercel with a fallback, gives up on Direct after 3 s", async () => {
    const { supadataCalls, outcome } = await runWithHangingYoutube(
      { supadataApiKey: "sd_x", onVercel: true },
      3_000,
    );
    expect(supadataCalls).toEqual(["/v1/transcript"]);
    expect(await outcome).toMatchObject({
      provider: "supadata",
      attempts: [{ provider: "direct", code: "UPSTREAM_TIMEOUT" }],
    });
  });

  it("on Vercel it has not given up a moment earlier", async () => {
    const { supadataCalls } = await runWithHangingYoutube(
      { supadataApiKey: "sd_x", onVercel: true },
      2_999,
    );
    expect(supadataCalls).toEqual([]);
  });

  it("locally it waits the full 15 s before falling through", async () => {
    const early = await runWithHangingYoutube(
      { supadataApiKey: "sd_x", onVercel: false },
      14_999,
    );
    expect(early.supadataCalls).toEqual([]);
    await vi.advanceTimersByTimeAsync(1);
    expect(early.supadataCalls).toEqual(["/v1/transcript"]);
    expect(await early.outcome).toMatchObject({ provider: "supadata" });
  });

  it("on Vercel without a fallback keeps the long timeout", async () => {
    const { outcome } = await runWithHangingYoutube(
      { supadataApiKey: undefined, onVercel: true },
      14_999,
    );
    let settled = false;
    void outcome.then(() => (settled = true));
    await vi.advanceTimersByTimeAsync(0);
    expect(settled).toBe(false);
    await vi.advanceTimersByTimeAsync(1);
    expect(await outcome).toMatchObject({ code: "UPSTREAM_TIMEOUT" });
  });
});
