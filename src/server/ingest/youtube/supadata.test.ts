import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { createSupadataProvider } from "./supadata";
import { TranscriptError, type TranscriptErrorCode } from "./provider";

const ID = "dQw4w9WgXcQ";
const KEY = "sd_test_key";
const signal = () => new AbortController().signal;

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json" },
  });

const chunks = [
  { text: "Never gonna", offset: 1200, duration: 2000, lang: "en" },
  { text: "give you up", offset: 3500, duration: 1500, lang: "en" },
];
const transcriptBody = { content: chunks, lang: "en", availableLangs: ["en"] };

type Handler = (
  url: URL,
  init: RequestInit | undefined,
) => Response | Promise<Response>;

/** Routes by host: Supadata, and YouTube's oEmbed for the title. */
function stubFetch(handlers: { supadata?: Handler; oembed?: Handler }) {
  const calls: Array<{ url: URL; init?: RequestInit }> = [];
  const mock = vi.fn(
    async (input: string | URL | Request, init?: RequestInit) => {
      const url = new URL(typeof input === "string" ? input : input.toString());
      calls.push({ url, init });
      const handler =
        url.hostname === "api.supadata.ai"
          ? handlers.supadata
          : url.pathname === "/oembed"
            ? handlers.oembed
            : undefined;
      if (!handler) throw new Error(`unexpected request: ${url}`);
      const pending = Promise.resolve(handler(url, init));
      const abort = init?.signal;
      if (!abort) return pending;
      // Real fetch rejects as soon as its signal aborts.
      return new Promise<Response>((resolve, reject) => {
        abort.addEventListener("abort", () => reject(abort.reason), {
          once: true,
        });
        pending.then(resolve, reject);
      });
    },
  );
  vi.stubGlobal("fetch", mock);
  return { calls, mock };
}

const okOembed: Handler = () =>
  json({ title: "Never Gonna Give You Up", author_name: "Rick Astley" });

const provider = () => createSupadataProvider({ apiKey: KEY });

async function expectCode(
  promise: Promise<unknown>,
  code: TranscriptErrorCode,
) {
  await expect(promise).rejects.toBeInstanceOf(TranscriptError);
  await expect(promise).rejects.toMatchObject({ code });
}

beforeEach(() => vi.useRealTimers());
afterEach(() => {
  vi.unstubAllGlobals();
  vi.useRealTimers();
});

describe("SupadataProvider: success", () => {
  it("maps the response and takes title and channel from oEmbed", async () => {
    stubFetch({ supadata: () => json(transcriptBody), oembed: okOembed });
    const result = await provider().fetch(ID, "en", signal());

    expect(result).toEqual({
      title: "Never Gonna Give You Up",
      channel: "Rick Astley",
      durationSec: 5, // last line ends at 3.5 s + 1.5 s
      language: "en",
      isAutoGenerated: null,
      segments: [
        { startMs: 1200, durMs: 2000, text: "Never gonna" },
        { startMs: 3500, durMs: 1500, text: "give you up" },
      ],
    });
  });

  it("sends the key, the canonical URL and native, timed mode", async () => {
    const { calls } = stubFetch({
      supadata: () => json(transcriptBody),
      oembed: okOembed,
    });
    await provider().fetch(ID, "en", signal());

    const call = calls.find((c) => c.url.hostname === "api.supadata.ai");
    expect(call?.url.pathname).toBe("/v1/transcript");
    expect(call?.url.searchParams.get("url")).toBe(
      `https://www.youtube.com/watch?v=${ID}`,
    );
    expect(call?.url.searchParams.get("mode")).toBe("native");
    expect(call?.url.searchParams.get("text")).toBe("false");
    expect(call?.url.searchParams.get("lang")).toBe("en");
    expect(call?.init?.headers).toEqual({ "x-api-key": KEY });
  });

  it.each([
    ["pt-BR", "pt"],
    ["FR", "fr"],
    ["de-DE", "de"],
  ])("sends the base language for %s", async (preferred, sent) => {
    const { calls } = stubFetch({
      supadata: () => json(transcriptBody),
      oembed: okOembed,
    });
    await provider().fetch(ID, preferred, signal());
    const call = calls.find((c) => c.url.hostname === "api.supadata.ai");
    expect(call?.url.searchParams.get("lang")).toBe(sent);
  });

  it("omits lang when it is not an ISO 639-1 code", async () => {
    const { calls } = stubFetch({
      supadata: () => json(transcriptBody),
      oembed: okOembed,
    });
    await provider().fetch(ID, "fil", signal());
    const call = calls.find((c) => c.url.hostname === "api.supadata.ai");
    expect(call?.url.searchParams.has("lang")).toBe(false);
  });

  it("reports the language Supadata actually served, not the one we asked for", async () => {
    stubFetch({
      supadata: () =>
        json({ ...transcriptBody, lang: "de", availableLangs: ["de", "en"] }),
      oembed: okOembed,
    });
    const result = await provider().fetch(ID, "fr", signal());
    expect(result.language).toBe("de");
  });

  it("collapses whitespace, drops sound tags and sorts by start", async () => {
    stubFetch({
      supadata: () =>
        json({
          lang: "en",
          content: [
            { text: "second\n line", offset: 4000, duration: 1000 },
            { text: "[Music]", offset: 0, duration: 1000 },
            { text: "  ", offset: 500, duration: 100 },
            { text: "first", offset: 2000 },
          ],
        }),
      oembed: okOembed,
    });
    const result = await provider().fetch(ID, "en", signal());
    expect(result.segments).toEqual([
      { startMs: 2000, durMs: 0, text: "first" },
      { startMs: 4000, durMs: 1000, text: "second line" },
    ]);
  });

  it("reports no captions for an empty transcript", async () => {
    stubFetch({
      supadata: () => json({ content: [], lang: "en", availableLangs: [] }),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "NO_CAPTIONS");
  });
});

describe("SupadataProvider: oEmbed is best effort", () => {
  it.each([
    ["a 404", () => new Response("", { status: 404 })],
    ["bad JSON", () => new Response("<html>")],
    ["the wrong shape", () => json({ nope: true })],
    ["an empty title", () => json({ title: "  " })],
    [
      "a network error",
      () => {
        throw new TypeError("fetch failed");
      },
    ],
  ] as Array<[string, Handler]>)(
    "falls back to a generic title on %s",
    async (_name, oembed) => {
      stubFetch({ supadata: () => json(transcriptBody), oembed });
      const result = await provider().fetch(ID, "en", signal());
      expect(result.title).toBe("YouTube video");
      expect(result.channel).toBe("");
      expect(result.segments).toHaveLength(2);
    },
  );

  it("waits at most 3 s for a hanging oEmbed", async () => {
    vi.useFakeTimers();
    stubFetch({
      supadata: () => json(transcriptBody),
      oembed: () => new Promise<Response>(() => undefined),
    });
    const pending = provider().fetch(ID, "en", signal());
    await vi.advanceTimersByTimeAsync(2_999);
    let settled = false;
    void pending.then(() => (settled = true));
    await vi.advanceTimersByTimeAsync(0);
    expect(settled).toBe(false);

    await vi.advanceTimersByTimeAsync(1);
    await expect(pending).resolves.toMatchObject({ title: "YouTube video" });
  });
});

describe("SupadataProvider: errors", () => {
  it("reads 206 as no captions even though it is a success status", async () => {
    stubFetch({
      supadata: () =>
        json(
          { error: "transcript-unavailable", message: "No transcript" },
          206,
        ),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "NO_CAPTIONS");
  });

  it.each([
    [429, "PROVIDER_QUOTA"],
    [402, "PROVIDER_QUOTA"],
    [404, "VIDEO_UNAVAILABLE"],
    [403, "AGE_RESTRICTED"],
    [400, "UPSTREAM_FAILED"],
    [401, "UPSTREAM_FAILED"],
    [500, "UPSTREAM_FAILED"],
    [502, "UPSTREAM_FAILED"],
  ] as const)("maps HTTP %s to %s", async (status, code) => {
    stubFetch({
      supadata: () => json({ error: "x", message: "boom" }, status),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), code);
  });

  it("never carries Supadata's error text into the error", async () => {
    stubFetch({
      supadata: () =>
        json(
          {
            error: "limit-exceeded",
            message: "SECRET upstream wording for key sd_live_abc",
          },
          429,
        ),
      oembed: okOembed,
    });
    const err = await provider()
      .fetch(ID, "en", signal())
      .catch((e: unknown) => e);
    expect(err).toBeInstanceOf(TranscriptError);
    expect(JSON.stringify(err)).not.toContain("SECRET");
    expect(String((err as Error).message)).not.toContain("SECRET");
    expect(String((err as Error).cause ?? "")).not.toContain("SECRET");
  });

  it("fails on a network error", async () => {
    stubFetch({
      supadata: () => {
        throw new TypeError("fetch failed");
      },
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });

  it("fails when the body is not the timed format", async () => {
    stubFetch({
      supadata: () => json({ content: "plain text, not chunks", lang: "en" }),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });

  it("fails when the body is not JSON", async () => {
    stubFetch({ supadata: () => new Response("<html>"), oembed: okOembed });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });

  it("times out after 15 s", async () => {
    vi.useFakeTimers();
    stubFetch({
      supadata: () => new Promise<Response>(() => undefined),
      oembed: okOembed,
    });
    const pending = provider().fetch(ID, "en", signal());
    const assertion = expectCode(pending, "UPSTREAM_TIMEOUT");
    await vi.advanceTimersByTimeAsync(15_000);
    await assertion;
  });

  it("passes a caller abort through instead of calling it a timeout", async () => {
    const controller = new AbortController();
    stubFetch({
      supadata: () => new Promise<Response>(() => undefined),
      oembed: okOembed,
    });
    const pending = provider().fetch(ID, "en", controller.signal);
    controller.abort(new DOMException("client left", "AbortError"));
    await expect(pending).rejects.not.toBeInstanceOf(TranscriptError);
  });
});

describe("SupadataProvider: async jobs", () => {
  const accepted = () => json({ jobId: "job_123" }, 202);

  it("polls a 202 job until it completes", async () => {
    vi.useFakeTimers();
    const statuses = ["queued", "active", "completed"];
    const { calls } = stubFetch({
      supadata: (url) => {
        if (url.pathname === "/v1/transcript") return accepted();
        const status = statuses.shift() ?? "completed";
        return json(
          status === "completed" ? { status, ...transcriptBody } : { status },
        );
      },
      oembed: okOembed,
    });

    const pending = provider().fetch(ID, "en", signal());
    await vi.advanceTimersByTimeAsync(5_000);
    const result = await pending;

    expect(result.segments).toHaveLength(2);
    const polls = calls.filter(
      (c) => c.url.pathname === "/v1/transcript/job_123",
    );
    expect(polls).toHaveLength(3);
    expect(polls[0]?.init?.headers).toEqual({ "x-api-key": KEY });
  });

  it("polls about once a second, not in a tight loop", async () => {
    vi.useFakeTimers();
    const { calls } = stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript"
          ? accepted()
          : json({ status: "active" }),
      oembed: okOembed,
    });
    const pending = provider().fetch(ID, "en", signal());
    const assertion = expectCode(pending, "UPSTREAM_TIMEOUT");
    await vi.advanceTimersByTimeAsync(10_500);
    const polls = calls.filter((c) =>
      c.url.pathname.startsWith("/v1/transcript/"),
    );
    expect(polls.length).toBeGreaterThanOrEqual(10);
    expect(polls.length).toBeLessThanOrEqual(12);
    await vi.advanceTimersByTimeAsync(30_000);
    await assertion;
  });

  it("gives up after 30 s of polling", async () => {
    vi.useFakeTimers();
    stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript"
          ? accepted()
          : json({ status: "queued" }),
      oembed: okOembed,
    });
    const pending = provider().fetch(ID, "en", signal());
    const assertion = expectCode(pending, "UPSTREAM_TIMEOUT");
    await vi.advanceTimersByTimeAsync(29_900);
    let settled = false;
    pending.catch(() => (settled = true));
    await vi.advanceTimersByTimeAsync(0);
    expect(settled).toBe(false);
    await vi.advanceTimersByTimeAsync(100);
    await assertion;
  });

  it("fails when the job fails", async () => {
    stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript"
          ? accepted()
          : json({ status: "failed", error: "SECRET internal" }),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });

  it("treats an expired job (404) as a failure, not a missing video", async () => {
    stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript" ? accepted() : json({}, 404),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });

  it("maps quota errors while polling too", async () => {
    stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript" ? accepted() : json({}, 429),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "PROVIDER_QUOTA");
  });

  it("reads a 206 while polling as no captions", async () => {
    stubFetch({
      supadata: (url) =>
        url.pathname === "/v1/transcript" ? accepted() : json({}, 206),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "NO_CAPTIONS");
  });

  it("refuses a job id that could change the poll URL", async () => {
    const { calls } = stubFetch({
      supadata: () => json({ jobId: "../../v1/other?x=1" }, 202),
      oembed: okOembed,
    });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
    expect(calls.filter((c) => c.url.pathname !== "/oembed")).toHaveLength(1);
  });

  it("fails on a 202 without a job id", async () => {
    stubFetch({ supadata: () => json({}, 202), oembed: okOembed });
    await expectCode(provider().fetch(ID, "en", signal()), "UPSTREAM_FAILED");
  });
});
