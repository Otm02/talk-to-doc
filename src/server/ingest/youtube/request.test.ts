const holder = vi.hoisted(() => ({
  state: undefined as StateAdapters | undefined,
}));
vi.mock("@/server/state", () => ({
  getState: () => {
    if (!holder.state) throw new Error("test state not set");
    return holder.state;
  },
}));

const URL_OK = "https://www.youtube.com/watch?v=dQw4w9WgXcQ";
const IP = { "x-forwarded-for": "203.0.113.9" };

function transcriptOf(lines: number, overrides: Partial<Transcript> = {}) {
  const segments = Array.from({ length: lines }, (_, i) => ({
    startMs: i * 5_000,
    durMs: 4_000,
    text: `line ${i} alpha beta gamma delta epsilon zeta eta theta`,
  }));
  return {
    title: "A long talk",
    channel: "Some Channel",
    durationSec: Math.ceil((lines * 5_000) / 1000),
    language: "en",
    isAutoGenerated: false,
    segments,
    ...overrides,
  } satisfies Transcript;
}

function fakeChain(
  outcome: Transcript | TranscriptErrorCode,
  extra: Partial<ChainResult> = {},
) {
  const fetch = vi.fn<TranscriptChain["fetch"]>(async () => {
    if (typeof outcome === "string") throw new TranscriptError(outcome);
    return {
      transcript: outcome,
      provider: "direct",
      attempts: [],
      ...extra,
    };
  });
  return { chain: { fetch } satisfies TranscriptChain, fetch };
}

function post(body: unknown, headers: Record<string, string> = IP) {
  return new Request("http://localhost/api/ingest/youtube", {
    method: "POST",
    headers,
    body: typeof body === "string" ? body : JSON.stringify(body),
  });
}

const run = (chain: TranscriptChain, req: Request) =>
  handle((r, id) => ingestYoutube(r, id, { chain }))(req);

async function readLines(res: Response): Promise<IngestLine[]> {
  if (!res.body) throw new Error("no body");
  const out: IngestLine[] = [];
  for await (const line of readNdjson(res.body, IngestLineSchema))
    out.push(line);
  return out;
}

async function expectError(res: Response, code: keyof typeof ERROR_CATALOG) {
  expect(res.status).toBe(ERROR_CATALOG[code].status);
  const body = await res.json();
  expect(body.error).toEqual({ code, message: ERROR_CATALOG[code].message });
  expect(typeof body.requestId).toBe("string");
}

beforeEach(() => {
  holder.state = createMemoryAdapters();
  resetEnvCacheForTests();
  vi.spyOn(console, "error").mockImplementation(() => undefined);
  vi.spyOn(console, "info").mockImplementation(() => undefined);
});
afterEach(() => {
  vi.unstubAllEnvs();
  resetEnvCacheForTests();
  vi.restoreAllMocks();
});

describe("ingestYoutube: the stream", () => {
  it("sends meta, one line per ~30 s paragraph, then done", async () => {
    const { chain } = fakeChain(transcriptOf(20)); // 100 s of captions
    const res = await run(chain, post({ url: URL_OK }));

    expect(res.status).toBe(200);
    expect(res.headers.get("content-type")).toBe(
      "application/x-ndjson; charset=utf-8",
    );
    expect(res.headers.get("cache-control")).toBe("no-store");

    const lines = await readLines(res);
    const meta = lines[0] as YoutubeMetaLine;
    expect(meta).toMatchObject({
      sourceType: "youtube",
      videoId: "dQw4w9WgXcQ",
      title: "A long talk",
      channel: "Some Channel",
      durationSec: 100,
      language: "en",
      isAutoGenerated: false,
      provider: "direct",
      cached: false,
      thumbnailUrl: "https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg",
    });

    const segments = lines.filter((l) => "segment" in l);
    expect(segments.map((l) => "segment" in l && l.segment.startSec)).toEqual([
      0, 30, 60, 90,
    ]);
    const done = lines[lines.length - 1];
    expect(done).toMatchObject({
      done: true,
      stats: { segments: 4 },
      coverage: 1,
    });
  });

  it("stores the [mm:ss] context under the document id with the PDF's TTL", async () => {
    const { chain } = fakeChain(transcriptOf(20));
    const res = await run(chain, post({ url: URL_OK }));
    const [meta] = await readLines(res);
    if (!meta || !("documentId" in meta)) throw new Error("no meta");

    const record = (await holder.state?.documents.get(
      meta.documentId,
    )) as YoutubeDocumentRecord | null;
    expect(record).toMatchObject({
      id: meta.documentId,
      sourceType: "youtube",
      videoId: "dQw4w9WgXcQ",
      title: "A long talk",
      coverage: 1,
    });
    expect(record?.context.startsWith("[00:00] line 0 alpha")).toBe(true);
    expect(record?.context).toContain("\n\n[00:30] line 6");
    expect(record?.stats.tokens).toBeGreaterThan(0);
  });

  it("uses h:mm:ss markers past one hour", async () => {
    // The default budget would cut the context before the one-hour mark.
    vi.stubEnv("CONTEXT_TOKEN_BUDGET", "60000");
    resetEnvCacheForTests();
    const { chain } = fakeChain(transcriptOf(800)); // 4000 s
    const res = await run(chain, post({ url: URL_OK }));
    const [meta] = await readLines(res);
    if (!meta || !("documentId" in meta)) throw new Error("no meta");
    const record = (await holder.state?.documents.get(
      meta.documentId,
    )) as YoutubeDocumentRecord;
    expect(record.context).toMatch(/\[1:00:00\] /);
  });

  it("cuts the stored context at CONTEXT_TOKEN_BUDGET but streams everything", async () => {
    vi.stubEnv("CONTEXT_TOKEN_BUDGET", "1000");
    resetEnvCacheForTests();
    const { chain } = fakeChain(transcriptOf(600)); // 50 min
    const res = await run(chain, post({ url: URL_OK }));
    const lines = await readLines(res);

    const segments = lines.filter((l) => "segment" in l);
    expect(segments).toHaveLength(100); // all 30 s paragraphs reach the preview

    const done = lines[lines.length - 1];
    if (!done || !("done" in done)) throw new Error("no done line");
    expect(done.stats.tokens).toBeGreaterThan(1000);
    expect(done.coverage).toBeCloseTo(1000 / done.stats.tokens, 5);
    expect(done.coverage).toBeLessThan(1);

    const meta = lines[0];
    if (!meta || !("documentId" in meta)) throw new Error("no meta");
    const record = (await holder.state?.documents.get(
      meta.documentId,
    )) as YoutubeDocumentRecord;
    expect(record.context.length).toBeLessThan(
      // The text on the wire is much larger than what the model keeps.
      segments.reduce(
        (n, l) => n + ("segment" in l ? l.segment.text.length : 0),
        0,
      ),
    );
    // Whole paragraphs only: it ends where a paragraph ends.
    expect(record.context).not.toMatch(/\[\d\d:\d\d\]\s*$/);
  });

  it("passes the browser language to the chain, defaulting to English", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    await run(chain, post({ url: URL_OK, lang: "fr-CA" }));
    await run(chain, post({ url: URL_OK.replace("Q", "R") }));
    expect(fetch.mock.calls[0]?.[1]).toBe("fr-CA");
    expect(fetch.mock.calls[1]?.[1]).toBe("en");
  });

  it("accepts every URL shape the parser does, and a bare id", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    for (const url of [
      "https://youtu.be/dQw4w9WgXcQ?si=abc",
      "https://www.youtube.com/shorts/aaaaaaaaaaa",
      "bbbbbbbbbbb",
    ]) {
      expect((await run(chain, post({ url }))).status).toBe(200);
    }
    expect(fetch.mock.calls.map((c) => c[0])).toEqual([
      "dQw4w9WgXcQ",
      "aaaaaaaaaaa",
      "bbbbbbbbbbb",
    ]);
  });

  it("strips control and bidi characters from the title", async () => {
    const { chain } = fakeChain(
      transcriptOf(3, {
        title: "Hi\u202Ethere\u0000 now",
        channel: "A\u2066B",
      }),
    );
    const [meta] = await readLines(await run(chain, post({ url: URL_OK })));
    expect(meta).toMatchObject({ title: "Hi there now", channel: "A B" });
  });

  it("reports an unknown auto-caption status as null", async () => {
    const { chain } = fakeChain(transcriptOf(3, { isAutoGenerated: null }), {
      provider: "supadata",
    });
    const [meta] = await readLines(await run(chain, post({ url: URL_OK })));
    expect(meta).toMatchObject({ isAutoGenerated: null, provider: "supadata" });
  });
});

describe("ingestYoutube: the transcript cache", () => {
  it("fetches once for the same video, then serves from the cache", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(10), {
      provider: "supadata",
    });

    const first = await readLines(await run(chain, post({ url: URL_OK })));
    const second = await readLines(await run(chain, post({ url: URL_OK })));

    expect(fetch).toHaveBeenCalledTimes(1);
    expect(first[0]).toMatchObject({ cached: false, provider: "supadata" });
    // The cache remembers which provider actually served it.
    expect(second[0]).toMatchObject({ cached: true, provider: "supadata" });
    // Same content, but each ingest is its own document.
    if (!first[0] || !second[0]) throw new Error("no meta");
    expect("documentId" in first[0] && "documentId" in second[0]).toBe(true);
    expect((first[0] as YoutubeMetaLine).documentId).not.toBe(
      (second[0] as YoutubeMetaLine).documentId,
    );
    expect(first.slice(1)).toEqual(second.slice(1));
  });

  it("hits the cache for a different URL shape of the same video", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    await run(chain, post({ url: URL_OK }));
    await run(chain, post({ url: "https://youtu.be/dQw4w9WgXcQ?t=5" }));
    expect(fetch).toHaveBeenCalledTimes(1);
  });

  it("does not share between languages", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    await run(chain, post({ url: URL_OK, lang: "en" }));
    await run(chain, post({ url: URL_OK, lang: "de" }));
    expect(fetch).toHaveBeenCalledTimes(2);
  });

  it("does not cache failures", async () => {
    const { chain, fetch } = fakeChain("BLOCKED");
    await run(chain, post({ url: URL_OK }));
    await run(chain, post({ url: URL_OK }));
    expect(fetch).toHaveBeenCalledTimes(2);
  });

  it("still ingests when the cache cannot be written", async () => {
    vi.spyOn(console, "warn").mockImplementation(() => undefined);
    const real = holder.state?.documents;
    if (!real || !holder.state) throw new Error("no state");
    holder.state = {
      ...holder.state,
      documents: {
        get: real.get.bind(real),
        delete: real.delete.bind(real),
        put: async (id, doc, ttl) => {
          if (id.startsWith("yt:")) throw new Error("redis down");
          return real.put(id, doc, ttl);
        },
      },
    };
    const { chain } = fakeChain(transcriptOf(3));
    expect((await run(chain, post({ url: URL_OK }))).status).toBe(200);
  });
});

describe("ingestYoutube: refusals happen before the stream", () => {
  it.each([
    ["not a url", "hello", "youtube_bad_url"],
    ["another host", "https://vimeo.com/123456789", "youtube_bad_url"],
    [
      "a lookalike host",
      "https://youtube.com.evil.com/watch?v=dQw4w9WgXcQ",
      "youtube_bad_url",
    ],
    [
      "a playlist",
      "https://www.youtube.com/playlist?list=PLabc",
      "youtube_no_video_id",
    ],
    ["a channel", "https://www.youtube.com/@creator", "youtube_no_video_id"],
  ] as const)("%s", async (_name, url, code) => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    await expectError(await run(chain, post({ url })), code);
    expect(fetch).not.toHaveBeenCalled();
  });

  it.each([
    ["NO_CAPTIONS", "youtube_no_transcript"],
    ["VIDEO_UNAVAILABLE", "youtube_unavailable"],
    ["AGE_RESTRICTED", "youtube_age_restricted"],
    ["LIVE_NOT_SUPPORTED", "youtube_live"],
    ["BLOCKED", "youtube_blocked"],
    ["UPSTREAM_TIMEOUT", "youtube_failed"],
    ["UPSTREAM_FAILED", "youtube_failed"],
    ["PROVIDER_QUOTA", "youtube_quota"],
  ] as const)("maps %s to %s with the catalog copy", async (code, expected) => {
    const { chain } = fakeChain(code);
    await expectError(await run(chain, post({ url: URL_OK })), expected);
  });

  it("never lets upstream wording reach the client", async () => {
    const chain: TranscriptChain = {
      fetch: async () => {
        throw new TranscriptError("UPSTREAM_FAILED", {
          cause: new Error("SECRET: Supadata said key sd_live_123 is bad"),
        });
      },
    };
    const res = await run(chain, post({ url: URL_OK }));
    const text = await res.text();
    expect(text).not.toContain("SECRET");
    expect(text).not.toContain("sd_live");
  });

  it("refuses a video longer than 6 hours", async () => {
    const { chain } = fakeChain(transcriptOf(3, { durationSec: 6 * 3600 + 1 }));
    await expectError(
      await run(chain, post({ url: URL_OK })),
      "youtube_too_long",
    );
  });

  it("accepts a video of exactly 6 hours", async () => {
    const { chain } = fakeChain(transcriptOf(3, { durationSec: 6 * 3600 }));
    expect((await run(chain, post({ url: URL_OK }))).status).toBe(200);
  });

  it("refuses a transcript over 1.5 million characters", async () => {
    const big = transcriptOf(3, {
      segments: [{ startMs: 0, durMs: 1, text: "x".repeat(1_500_001) }],
    });
    const { chain } = fakeChain(big);
    await expectError(
      await run(chain, post({ url: URL_OK })),
      "youtube_too_long",
    );
  });

  it.each([
    ["not JSON", "{nope"],
    ["no url", {}],
    ["an empty url", { url: "" }],
    ["an extra field", { url: URL_OK, extra: 1 }],
    ["a bad lang", { url: URL_OK, lang: "not a lang!" }],
    ["a non-string url", { url: 5 }],
  ])("rejects a malformed body: %s", async (_name, body) => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    await expectError(await run(chain, post(body)), "invalid_request");
    expect(fetch).not.toHaveBeenCalled();
  });

  it("rate limits per client before doing anything else", async () => {
    const { chain, fetch } = fakeChain(transcriptOf(3));
    for (let i = 0; i < 10; i += 1) {
      expect((await run(chain, post({ url: URL_OK }))).status).toBe(200);
    }
    const blocked = await run(chain, post({ url: URL_OK }));
    await expectError(blocked, "rate_limited");
    expect(Number(blocked.headers.get("retry-after"))).toBeGreaterThan(0);
    expect(fetch).toHaveBeenCalledTimes(1); // the rest were cache hits

    // A different client has its own allowance.
    const other = await run(
      chain,
      post({ url: URL_OK }, { "x-forwarded-for": "198.51.100.7" }),
    );
    expect(other.status).toBe(200);
  });
});

describe("ingestYoutube: logging", () => {
  it("logs the provider and counts, never transcript text or the raw URL", async () => {
    const info = vi.spyOn(console, "info").mockImplementation(() => undefined);
    const { chain } = fakeChain(transcriptOf(10), {
      provider: "supadata",
      attempts: [{ provider: "direct", code: "BLOCKED" }],
    });
    await run(chain, post({ url: `${URL_OK}&si=tracking-token` }));

    expect(info).toHaveBeenCalledTimes(1);
    const line = String(info.mock.calls[0]?.[0]);
    expect(JSON.parse(line)).toMatchObject({
      event: "youtube_ingest",
      videoId: "dQw4w9WgXcQ",
      provider: "supadata",
      cached: false,
      attempts: [{ provider: "direct", code: "BLOCKED" }],
      segments: 2,
    });
    expect(line).not.toContain("alpha");
    expect(line).not.toContain("A long talk");
    expect(line).not.toContain("tracking-token");
  });
});
