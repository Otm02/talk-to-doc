import { describe, expect, it, vi } from "vitest";
import { createMemoryAdapters } from "../../state/memory";
import type { DocumentStore } from "../../state";
import {
  cacheKey,
  readCachedTranscript,
  writeCachedTranscript,
  type CachedTranscript,
} from "./cache";

const entry = (text = "hello"): CachedTranscript => ({
  provider: "supadata",
  transcript: {
    title: "A talk",
    channel: "Someone",
    durationSec: 30,
    language: "en",
    isAutoGenerated: null,
    segments: [{ startMs: 0, durMs: 1000, text }],
  },
});

function setup() {
  let now = 1_000_000;
  const adapters = createMemoryAdapters({ now: () => now });
  return {
    store: adapters.documents,
    advance: (ms: number) => {
      now += ms;
    },
  };
}

describe("cacheKey", () => {
  it("is per video and base language", () => {
    expect(cacheKey("abc", "en")).toBe("yt:abc:en");
    expect(cacheKey("abc", "pt-BR")).toBe("yt:abc:pt");
    expect(cacheKey("abc", "PT")).toBe("yt:abc:pt");
    expect(cacheKey("abc", "")).toBe("yt:abc:en");
  });
});

describe("transcript cache", () => {
  it("round-trips a transcript with its provider", async () => {
    const { store } = setup();
    expect(await writeCachedTranscript(store, "vid", "en", entry())).toBe(true);
    expect(await readCachedTranscript(store, "vid", "en")).toEqual(entry());
  });

  it("misses for another video or another language", async () => {
    const { store } = setup();
    await writeCachedTranscript(store, "vid", "en", entry());
    expect(await readCachedTranscript(store, "other", "en")).toBeNull();
    expect(await readCachedTranscript(store, "vid", "fr")).toBeNull();
  });

  it("shares an entry between en and en-GB", async () => {
    const { store } = setup();
    await writeCachedTranscript(store, "vid", "en-GB", entry());
    expect(await readCachedTranscript(store, "vid", "en-US")).toEqual(entry());
  });

  it("expires after an hour", async () => {
    const { store, advance } = setup();
    await writeCachedTranscript(store, "vid", "en", entry());

    advance(60 * 60_000 - 1);
    expect(await readCachedTranscript(store, "vid", "en")).not.toBeNull();
    advance(1);
    expect(await readCachedTranscript(store, "vid", "en")).toBeNull();
  });

  it("does not store a transcript too big for Upstash, and says so", async () => {
    const { store } = setup();
    const huge = entry("x".repeat(600_000));
    expect(await writeCachedTranscript(store, "vid", "en", huge)).toBe(false);
    expect(await readCachedTranscript(store, "vid", "en")).toBeNull();
  });

  it("treats a malformed entry as a miss", async () => {
    const { store } = setup();
    await store.put("yt:vid:en", { provider: "nobody", transcript: 3 }, 60_000);
    expect(await readCachedTranscript(store, "vid", "en")).toBeNull();
  });

  it("treats a store that throws as a miss, not an error", async () => {
    vi.spyOn(console, "warn").mockImplementation(() => undefined);
    const broken: DocumentStore = {
      get: async () => {
        throw new Error("redis down");
      },
      put: async () => {
        throw new Error("redis down");
      },
      delete: async () => undefined,
    };
    expect(await readCachedTranscript(broken, "vid", "en")).toBeNull();
    expect(await writeCachedTranscript(broken, "vid", "en", entry())).toBe(
      false,
    );
    vi.restoreAllMocks();
  });
});
