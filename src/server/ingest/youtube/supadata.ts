import "server-only";
import { z } from "zod";
import { canonicalUrl } from "@/lib/youtube/parseUrl";
import { collapseWhitespace, isSoundTagOnly } from "./captionsXml";
import { withDeadline } from "./deadline";
import {
  SUPADATA_POLL_CAP_MS,
  SUPADATA_POLL_INTERVAL_MS,
  SUPADATA_TIMEOUT_MS,
} from "./limits";
import { fetchVideoInfo } from "./oembed";
import {
  TranscriptError,
  type Transcript,
  type TranscriptProvider,
  type TranscriptSegment,
} from "./provider";

/**
 * Hosted transcripts through Supadata, per docs/reference/youtube-transcripts.md
 * section 3. This is the path that works from Vercel, where YouTube blocks
 * direct fetching. `mode=native` only: existing captions, 1 credit, never the
 * AI-generated transcript that costs 2 credits a minute.
 */

const ENDPOINT = "https://api.supadata.ai/v1/transcript";
const JOB_ID = /^[A-Za-z0-9_-]{1,128}$/;

const PayloadSchema = z.object({
  // text=false gives timed chunks; a plain string here means a changed API.
  content: z.array(
    z.object({
      text: z.string(),
      offset: z.number(),
      duration: z.number().optional(),
    }),
  ),
  lang: z.string().optional(),
});
type Payload = z.infer<typeof PayloadSchema>;

const JobSchema = z.object({
  status: z.enum(["queued", "active", "completed", "failed"]),
  content: z.unknown().optional(),
  lang: z.string().optional(),
});
const AcceptedSchema = z.object({ jobId: z.string() });

export interface SupadataOptions {
  apiKey: string;
}

export function createSupadataProvider(
  options: SupadataOptions,
): TranscriptProvider {
  const headers = { "x-api-key": options.apiKey };

  return {
    name: "supadata",
    async fetch(videoId, preferredLang, signal): Promise<Transcript> {
      // Title and channel are not in Supadata's answer; ask in parallel.
      const info = fetchVideoInfo(videoId, signal);

      const url = new URL(ENDPOINT);
      url.searchParams.set("url", canonicalUrl(videoId));
      url.searchParams.set("text", "false");
      url.searchParams.set("mode", "native");
      // Supadata wants ISO 639-1; a regional or 3-letter tag is not one.
      const lang = preferredLang.toLowerCase().split("-")[0] ?? "";
      if (/^[a-z]{2}$/.test(lang)) url.searchParams.set("lang", lang);

      const first = await withDeadline(signal, SUPADATA_TIMEOUT_MS, (attempt) =>
        fetch(url, { headers, signal: attempt }).then((res) =>
          readFirstAnswer(res),
        ),
      );
      const payload =
        first.kind === "done"
          ? first.payload
          : await pollJob(first.jobId, headers, signal);

      const segments = toSegments(payload);
      if (segments.length === 0) throw new TranscriptError("NO_CAPTIONS");

      const last = segments[segments.length - 1];
      const meta = await info;
      return {
        title: meta?.title ?? "YouTube video",
        channel: meta?.channel ?? "",
        // Supadata does not send the length; the last line is the best guess.
        durationSec: last ? Math.ceil((last.startMs + last.durMs) / 1000) : 0,
        language: payload.lang ?? (lang || "en"),
        // Supadata does not say whether captions are machine-made.
        isAutoGenerated: null,
        segments,
      };
    },
  };
}

type FirstAnswer =
  { kind: "done"; payload: Payload } | { kind: "job"; jobId: string };

/** 206 and 202 are success-range statuses with their own meaning, so this checks them before `ok`. */
async function readFirstAnswer(res: Response): Promise<FirstAnswer> {
  if (res.status === 206) throw new TranscriptError("NO_CAPTIONS");
  if (res.status === 202) {
    const accepted = AcceptedSchema.safeParse(await res.json());
    if (!accepted.success || !JOB_ID.test(accepted.data.jobId)) {
      throw new TranscriptError("UPSTREAM_FAILED", {
        cause: new Error("Unrecognised 202 body"),
      });
    }
    return { kind: "job", jobId: accepted.data.jobId };
  }
  if (res.status !== 200) throw errorForStatus(res.status);
  return { kind: "done", payload: parsePayload(await res.json()) };
}

async function pollJob(
  jobId: string,
  headers: Record<string, string>,
  signal: AbortSignal,
): Promise<Payload> {
  // Polling is free, so the cap is about the user's patience, not credits.
  return withDeadline(signal, SUPADATA_POLL_CAP_MS, async (attempt) => {
    for (;;) {
      const res = await fetch(`${ENDPOINT}/${jobId}`, {
        headers,
        signal: attempt,
      });
      if (res.status === 206) throw new TranscriptError("NO_CAPTIONS");
      // A 404 here is an expired job, not a missing video.
      if (res.status === 404) {
        throw new TranscriptError("UPSTREAM_FAILED", {
          cause: new Error("Job expired"),
        });
      }
      if (res.status !== 200) throw errorForStatus(res.status);

      const job = JobSchema.safeParse(await res.json());
      if (!job.success) {
        throw new TranscriptError("UPSTREAM_FAILED", { cause: job.error });
      }
      if (job.data.status === "failed") {
        throw new TranscriptError("UPSTREAM_FAILED", {
          cause: new Error("Supadata job failed"),
        });
      }
      if (job.data.status === "completed") {
        return parsePayload(job.data);
      }
      await sleep(SUPADATA_POLL_INTERVAL_MS, attempt);
    }
  });
}

function parsePayload(body: unknown): Payload {
  const parsed = PayloadSchema.safeParse(body);
  if (!parsed.success) {
    throw new TranscriptError("UPSTREAM_FAILED", { cause: parsed.error });
  }
  return parsed.data;
}

function toSegments(payload: Payload): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  for (const chunk of payload.content) {
    const text = collapseWhitespace(chunk.text);
    if (text === "" || isSoundTagOnly(text)) continue;
    // offset and duration are milliseconds, unlike YouTube's seconds.
    segments.push({
      startMs: Math.max(0, Math.round(chunk.offset)),
      durMs: Math.max(0, Math.round(chunk.duration ?? 0)),
      text,
    });
  }
  return segments.sort((a, b) => a.startMs - b.startMs);
}

/**
 * Supadata's status is the signal; its error body (which can carry upstream
 * text) is never read. 403 is "needs auth or restricted"; SPEC §5.2 maps it to
 * age-restricted, the common case for a public video.
 */
function errorForStatus(status: number): TranscriptError {
  switch (status) {
    case 402: // plan does not include this
    case 429: // rate or credit limit: indistinguishable by status
      return new TranscriptError("PROVIDER_QUOTA");
    case 403:
      return new TranscriptError("AGE_RESTRICTED");
    case 404:
      return new TranscriptError("VIDEO_UNAVAILABLE");
    default:
      // 400 (our request), 401 (our key), 5xx (theirs).
      return new TranscriptError("UPSTREAM_FAILED", {
        cause: new Error(`Supadata HTTP ${status}`),
      });
  }
}

function sleep(ms: number, signal: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal.aborted) return reject(signal.reason);
    const timer = setTimeout(() => {
      signal.removeEventListener("abort", onAbort);
      resolve();
    }, ms);
    const onAbort = () => {
      clearTimeout(timer);
      reject(signal.reason);
    };
    signal.addEventListener("abort", onAbort, { once: true });
  });
}
