import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { youtubeFixture } from "@test/fixtures";
import { playerWith, stubYoutube, type Routes } from "@test/youtubeFetch";
import { createDirectProvider } from "./direct";
import { TranscriptError, type TranscriptErrorCode } from "./provider";

const LOCAL = { timeoutMs: 15_000, networkRetries: 1 };
const FAST_FAIL = { timeoutMs: 3_000, networkRetries: 0 };
const ID = "jNQXAC9IVRw";
const signal = () => new AbortController().signal;

async function expectCode(
  promise: Promise<unknown>,
  code: TranscriptErrorCode,
): Promise<void> {
  await expect(promise).rejects.toBeInstanceOf(TranscriptError);
  await expect(promise).rejects.toMatchObject({ code });
}

beforeEach(() => {
  vi.useRealTimers();
});
afterEach(() => {
  vi.unstubAllGlobals();
  vi.useRealTimers();
});

describe("DirectProvider with recorded responses", () => {
  it("reads manual captions and the video details", async () => {
    stubYoutube("manual");
    const result = await createDirectProvider(LOCAL).fetch(ID, "en", signal());

    expect(result).toMatchObject({
      title: "Me at the zoo",
      channel: "jawed",
      durationSec: 19,
      language: "en",
      isAutoGenerated: false,
    });
    expect(result.segments.length).toBeGreaterThan(3);
    expect(result.segments[0]).toMatchObject({ startMs: 1200, durMs: 2160 });
    expect(result.segments[0]?.text).toContain("All right, so here we are");
    // Lines wrapped inside <text> come back as one line.
    expect(result.segments.every((s) => !s.text.includes("\n"))).toBe(true);
  });

  it("picks the requested language when it exists", async () => {
    stubYoutube("manual");
    const result = await createDirectProvider(LOCAL).fetch(ID, "de", signal());
    expect(result.language).toBe("de");
    expect(result.isAutoGenerated).toBe(false);
  });

  it("falls back to English when the requested language is missing", async () => {
    stubYoutube("manual");
    const result = await createDirectProvider(LOCAL).fetch(ID, "fr", signal());
    expect(result.language).toBe("en");
  });

  it("flags auto-generated captions and decodes their entities", async () => {
    stubYoutube("auto-only");
    const result = await createDirectProvider(LOCAL).fetch(
      "_OBlgSz8sSM",
      "en",
      signal(),
    );
    expect(result.isAutoGenerated).toBe(true);
    const text = result.segments.map((s) => s.text).join(" ");
    expect(text).toContain("it's still");
    expect(text).not.toContain("&#39;");
    expect(text).not.toContain("&amp;");
  });

  it("asks for plain XML, never srv3, and only talks to youtube.com", async () => {
    const { calls } = stubYoutube("manual");
    await createDirectProvider(LOCAL).fetch(ID, "en", signal());

    const caption = calls.find((c) => c.url.includes("/api/timedtext"));
    expect(caption?.url).not.toContain("fmt=srv3");
    for (const call of calls) {
      expect(new URL(call.url).hostname).toBe("www.youtube.com");
    }
  });

  it("posts the Android client context to the player endpoint", async () => {
    const { calls } = stubYoutube("manual");
    await createDirectProvider(LOCAL).fetch(ID, "en", signal());

    const player = calls.find((c) => c.url.includes("/youtubei/v1/player"));
    expect(player?.url).toMatch(/\?key=[A-Za-z0-9_-]+$/);
    expect(player?.init?.method).toBe("POST");
    expect(JSON.parse(String(player?.init?.body))).toEqual({
      context: { client: { clientName: "ANDROID", clientVersion: "20.10.38" } },
      videoId: ID,
    });
  });

  it("reports a video with captions turned off", async () => {
    stubYoutube("disabled");
    await expectCode(
      createDirectProvider(LOCAL).fetch("dMH0bHeiRNg", "en", signal()),
      "NO_CAPTIONS",
    );
  });

  it("reports a removed video", async () => {
    stubYoutube("unavailable");
    await expectCode(
      createDirectProvider(LOCAL).fetch("KmtzQCSh6xk", "en", signal()),
      "VIDEO_UNAVAILABLE",
    );
  });
});

describe("DirectProvider: blocks and consent", () => {
  it("clears the consent wall once with the cookie YouTube asks for", async () => {
    const wall = `<form action="https://consent.youtube.com/s"><input type="hidden" name="v" value="cb.20240101-00-p0.en+FX+123"></form>`;
    const { calls } = stubYoutube("manual", {
      watch: (n) =>
        n === 1
          ? new Response(wall)
          : new Response(youtubeFixture("manual").watchHtml),
    });

    const result = await createDirectProvider(LOCAL).fetch(ID, "en", signal());
    expect(result.language).toBe("en");

    const watches = calls.filter((c) => c.url.includes("/watch"));
    expect(watches).toHaveLength(2);
    expect(watches[1]?.init?.headers).toMatchObject({
      cookie: "CONSENT=YES+cb.20240101-00-p0.en+FX+123",
    });
  });

  it("is blocked when the consent wall comes back", async () => {
    const wall = `<form action="https://consent.youtube.com/s"><input name="v" value="abc"></form>`;
    stubYoutube("manual", { watch: () => new Response(wall) });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "BLOCKED",
    );
  });

  it("is blocked when the wall has no cookie value to send", async () => {
    stubYoutube("manual", {
      watch: () =>
        new Response(`<form action="https://consent.youtube.com/s"></form>`),
    });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "BLOCKED",
    );
  });

  it.each([
    ["watch page", { watch: () => new Response("", { status: 429 }) }],
    ["player", { player: () => new Response("", { status: 429 }) }],
    ["captions", { caption: () => new Response("", { status: 429 }) }],
  ] satisfies Array<[string, Routes]>)(
    "treats a 429 from the %s as an IP block, with no retry",
    async (_name, routes) => {
      const { fetchMock } = stubYoutube("manual", routes);
      await expectCode(
        createDirectProvider(LOCAL).fetch(ID, "en", signal()),
        "BLOCKED",
      );
      const hits429 = fetchMock.mock.calls.length;
      // Exactly one request per step reached; none repeated.
      expect(hits429).toBeLessThanOrEqual(3);
    },
  );

  it("is blocked by a captcha page with no API key", async () => {
    stubYoutube("manual", {
      watch: () => new Response('<div class="g-recaptcha"></div>'),
    });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "BLOCKED",
    );
  });

  it("fails (not blocked) when the page has no key and no captcha", async () => {
    stubYoutube("manual", { watch: () => new Response("<html></html>") });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "UPSTREAM_FAILED",
    );
  });

  it("is blocked by the bot check", async () => {
    stubYoutube("manual", {
      player: () =>
        new Response(
          playerWith("manual", (p) => {
            p.playabilityStatus = {
              status: "LOGIN_REQUIRED",
              reason: "Sign in to confirm you’re not a bot",
            };
          }),
        ),
    });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "BLOCKED",
    );
  });

  it("is blocked when the caption track needs a PO token, without fetching it", async () => {
    const { calls } = stubYoutube("manual", {
      player: () =>
        new Response(
          playerWith("manual", (p) => {
            for (const t of p.captions.playerCaptionsTracklistRenderer
              .captionTracks) {
              t.baseUrl += "&exp=xpe";
            }
          }),
        ),
    });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "BLOCKED",
    );
    expect(calls.some((c) => c.url.includes("/api/timedtext"))).toBe(false);
  });
});

describe("DirectProvider: playability", () => {
  const withStatus = (status: unknown, details?: Record<string, unknown>) => ({
    player: () =>
      new Response(
        playerWith("manual", (p) => {
          p.playabilityStatus = status;
          if (details) Object.assign(p.videoDetails ?? {}, details);
        }),
      ),
  });

  it.each([
    [
      "age-restricted (reason)",
      {
        status: "LOGIN_REQUIRED",
        reason: "This video may be inappropriate for some users.",
      },
      "AGE_RESTRICTED",
    ],
    ["age check required", { status: "AGE_CHECK_REQUIRED" }, "AGE_RESTRICTED"],
    [
      "error",
      { status: "ERROR", reason: "This video is unavailable" },
      "VIDEO_UNAVAILABLE",
    ],
    [
      "private (login required, other reason)",
      { status: "LOGIN_REQUIRED", reason: "This video is private" },
      "VIDEO_UNAVAILABLE",
    ],
    [
      "unplayable (region, members-only)",
      { status: "UNPLAYABLE", reason: "Not available in your country" },
      "VIDEO_UNAVAILABLE",
    ],
    [
      "a status nobody has seen",
      { status: "SOMETHING_NEW" },
      "VIDEO_UNAVAILABLE",
    ],
    [
      "live stream offline",
      { status: "LIVE_STREAM_OFFLINE" },
      "LIVE_NOT_SUPPORTED",
    ],
    ["no status at all", {}, "UPSTREAM_FAILED"],
  ] as const)("%s", async (_name, status, code) => {
    stubYoutube("manual", withStatus(status));
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      code,
    );
  });

  it("refuses a stream that is live right now", async () => {
    stubYoutube("manual", withStatus({ status: "OK" }, { isLive: true }));
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "LIVE_NOT_SUPPORTED",
    );
  });

  it("refuses an upcoming premiere or stream", async () => {
    stubYoutube("manual", withStatus({ status: "OK" }, { isUpcoming: true }));
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "LIVE_NOT_SUPPORTED",
    );
  });

  it("accepts a finished stream (isLiveContent but not live)", async () => {
    stubYoutube(
      "manual",
      withStatus({ status: "OK" }, { isLiveContent: true, isLive: false }),
    );
    const result = await createDirectProvider(LOCAL).fetch(ID, "en", signal());
    expect(result.segments.length).toBeGreaterThan(0);
  });

  it("fails when the player response is not JSON", async () => {
    stubYoutube("manual", { player: () => new Response("<html>nope</html>") });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "UPSTREAM_FAILED",
    );
  });

  it("fails when the player response has the wrong shape", async () => {
    stubYoutube("manual", {
      player: () =>
        new Response(JSON.stringify({ playabilityStatus: "OK", captions: 3 })),
    });
    await expectCode(
      createDirectProvider(LOCAL).fetch(ID, "en", signal()),
      "UPSTREAM_FAILED",
    );
  });

  it("uses a placeholder title and the caption length when details are missing", async () => {
    stubYoutube("manual", {
      player: () =>
        new Response(
          playerWith("manual", (p) => {
            delete p.videoDetails;
          }),
        ),
    });
    const result = await createDirectProvider(LOCAL).fetch(ID, "en", signal());
    expect(result.title).toBe("YouTube video");
    expect(result.channel).toBe("");
    expect(result.durationSec).toBeGreaterThan(0);
  });
});

