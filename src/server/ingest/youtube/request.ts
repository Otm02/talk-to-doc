import "server-only";
import {
  YoutubeIngestBodySchema,
  type IngestLine,
  type YoutubeStats,
} from "@/lib/wire/ingest";
import { encodeNdjsonLine } from "@/lib/wire/ndjson";
import { parseYoutubeUrl, thumbnailUrl } from "@/lib/youtube/parseUrl";
import { capToTokenBudget, countTokens } from "../../context/budget";
import { getEnv } from "../../env";
import { catalogError } from "../../errors";
import { parseWith } from "../../http";
import { enforceRateLimit } from "../../security/rate-limit";
import { getState } from "../../state";
import { cleanTitle } from "../pdf/title";
import { countWords } from "../pdf/normalize";
import type { YoutubeDocumentRecord } from "../record";
import {
  readCachedTranscript,
  writeCachedTranscript,
  type CachedTranscript,
} from "./cache";
import { renderForModel, toParagraphs } from "./format";
import {
  buildProviders,
  createChain,
  type Attempt,
  type TranscriptChain,
} from "./index";
import {
  DEFAULT_LANG,
  MAX_DURATION_SEC,
  MAX_TRANSCRIPT_CHARS,
  YOUTUBE_INGEST_RATE,
} from "./limits";
import { TranscriptError, toAppError } from "./provider";

export interface YoutubeIngestDeps {
  /** Tests pass a fake chain; production builds one from the env. */
  chain?: TranscriptChain;
  now?: () => number;
}

const encoder = new TextEncoder();

/**
 * POST /api/ingest/youtube { url, lang? }. Everything that can refuse
 * (rate limit, bad link, no captions, quota) happens before the first byte,
 * so it comes back as a normal JSON error with an HTTP status, like the PDF
 * route. After that the body is NDJSON: meta, one line per ~30 s paragraph,
 * then done.
 */
export async function ingestYoutube(
  req: Request,
  requestId: string,
  deps: YoutubeIngestDeps = {},
): Promise<Response> {
  const now = deps.now ?? Date.now;
  const startedAt = now();
  const env = getEnv();

  await enforceRateLimit(req, "ingest-youtube", YOUTUBE_INGEST_RATE);

  const body = parseWith(
    YoutubeIngestBodySchema,
    await req.json().catch(() => {
      throw catalogError("invalid_request");
    }),
  );
  const parsed = parseYoutubeUrl(body.url);
  if (!parsed.ok) {
    throw catalogError(
      parsed.reason === "no_video_id"
        ? "youtube_no_video_id"
        : "youtube_bad_url",
    );
  }
  const { videoId } = parsed;
  const lang = body.lang ?? DEFAULT_LANG;
  const store = getState().documents;

  let cached = true;
  let attempts: Attempt[] = [];
  let served = await readCachedTranscript(store, videoId, lang);
  if (!served) {
    cached = false;
    const chain = deps.chain ?? createChain(buildProviders(env));
    try {
      const result = await chain.fetch(videoId, lang, req.signal);
      served = { transcript: result.transcript, provider: result.provider };
      attempts = result.attempts;
    } catch (err) {
      if (err instanceof TranscriptError) throw toAppError(err);
      throw err;
    }
    await writeCachedTranscript(store, videoId, lang, served);
  }

  const { transcript, provider } = served;
  assertNotTooLong(served);

  const paragraphs = toParagraphs(transcript.segments);
  const fullText = renderForModel(paragraphs);
  const tokens = countTokens(fullText);
  const stats: YoutubeStats = {
    segments: paragraphs.length,
    words: paragraphs.reduce((n, p) => n + countWords(p.text), 0),
    tokens,
  };
  const coverage = Math.min(1, env.contextTokenBudget / Math.max(tokens, 1));
  const { text: context } = capToTokenBudget(
    fullText,
    env.contextTokenBudget,
    tokens,
  );

  const documentId = crypto.randomUUID();
  const title = cleanTitle(transcript.title) || "YouTube video";
  const record: YoutubeDocumentRecord = {
    id: documentId,
    sourceType: "youtube",
    videoId,
    title,
    context,
    stats,
    coverage,
    createdAt: now(),
  };
  await store.put(documentId, record, env.docTtlMinutes * 60_000);

  // Ids, counts and timings only. Never transcript text, never the raw URL.
  console.info(
    JSON.stringify({
      event: "youtube_ingest",
      requestId,
      videoId,
      provider,
      cached,
      attempts,
      segments: paragraphs.length,
      tokens,
      coverage: Number(coverage.toFixed(3)),
      ms: now() - startedAt,
    }),
  );

  const lines: IngestLine[] = [
    {
      documentId,
      title,
      sourceType: "youtube",
      videoId,
      thumbnailUrl: thumbnailUrl(videoId),
      channel: cleanTitle(transcript.channel),
      durationSec: Math.round(transcript.durationSec),
      language: transcript.language,
      isAutoGenerated: transcript.isAutoGenerated,
      provider,
      cached,
    },
    ...paragraphs.map((p) => ({
      segment: { startSec: p.startSec, text: p.text },
    })),
    { done: true, stats, coverage },
  ];

  return new Response(linesToStream(lines), {
    headers: {
      "content-type": "application/x-ndjson; charset=utf-8",
      "cache-control": "no-store",
    },
  });
}

/** SPEC §5.2: over 6 h or 1.5 M characters is refused rather than loaded. */
function assertNotTooLong({ transcript }: CachedTranscript): void {
  const chars = transcript.segments.reduce((n, s) => n + s.text.length, 0);
  if (
    transcript.durationSec > MAX_DURATION_SEC ||
    chars > MAX_TRANSCRIPT_CHARS
  ) {
    throw catalogError("youtube_too_long");
  }
}

/** One line per pull, so a slow reader slows us down instead of buffering. */
function linesToStream(
  lines: readonly IngestLine[],
): ReadableStream<Uint8Array> {
  let next = 0;
  return new ReadableStream<Uint8Array>({
    pull(controller) {
      const line = lines[next];
      if (line === undefined) {
        controller.close();
        return;
      }
      next += 1;
      controller.enqueue(encoder.encode(encodeNdjsonLine(line)));
    },
  });
}
