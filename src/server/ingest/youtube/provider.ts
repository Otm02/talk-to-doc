import "server-only";
import type { CatalogCode } from "@/lib/errors/catalog";
import type { TranscriptProviderName } from "@/lib/wire/ingest";
import { catalogError, type AppError } from "../../errors";

// A `type`, not an interface, so a Transcript is assignable to the store's
// JSON value type (it is cached through the DocumentStore).
export type TranscriptSegment = {
  startMs: number;
  durMs: number;
  text: string;
};

export type Transcript = {
  title: string;
  channel: string;
  durationSec: number;
  /** The language actually served, which may differ from the one asked for. */
  language: string;
  /** null when the provider cannot tell (Supadata does not say). */
  isAutoGenerated: boolean | null;
  segments: TranscriptSegment[];
};

export interface TranscriptProvider {
  readonly name: TranscriptProviderName;
  fetch(
    videoId: string,
    preferredLang: string,
    signal: AbortSignal,
  ): Promise<Transcript>;
}

export type TranscriptErrorCode =
  | "NO_CAPTIONS"
  | "VIDEO_UNAVAILABLE"
  | "AGE_RESTRICTED"
  | "LIVE_NOT_SUPPORTED"
  | "BLOCKED" // IP block, bot check, PO token, 429
  | "UPSTREAM_TIMEOUT"
  | "PROVIDER_QUOTA"
  | "UPSTREAM_FAILED"; // anything else that went wrong upstream

/** What a provider throws. Never carries text meant for the user. */
export class TranscriptError extends Error {
  constructor(
    readonly code: TranscriptErrorCode,
    options?: { cause?: unknown },
  ) {
    super(code, options);
    this.name = "TranscriptError";
  }
}

/**
 * The only errors that let the chain try the next provider. Everything else
 * is a fact about the video (or our quota), so another provider would give the
 * same answer and, for Supadata, burn a credit doing it.
 */
export function isRetryable(code: TranscriptErrorCode): boolean {
  switch (code) {
    case "BLOCKED":
    case "UPSTREAM_TIMEOUT":
    case "UPSTREAM_FAILED":
      return true;
    case "NO_CAPTIONS":
    case "VIDEO_UNAVAILABLE":
    case "AGE_RESTRICTED":
    case "LIVE_NOT_SUPPORTED":
    case "PROVIDER_QUOTA":
      return false;
  }
}

export function toCatalogCode(code: TranscriptErrorCode): CatalogCode {
  switch (code) {
    case "NO_CAPTIONS":
      return "youtube_no_transcript";
    case "VIDEO_UNAVAILABLE":
      return "youtube_unavailable";
    case "AGE_RESTRICTED":
      return "youtube_age_restricted";
    case "LIVE_NOT_SUPPORTED":
      return "youtube_live";
    case "BLOCKED":
      return "youtube_blocked";
    case "PROVIDER_QUOTA":
      return "youtube_quota";
    case "UPSTREAM_TIMEOUT":
    case "UPSTREAM_FAILED":
      return "youtube_failed";
  }
}

/** Turns a provider error into the AppError the route handler maps to JSON. */
export function toAppError(err: TranscriptError): AppError {
  return catalogError(toCatalogCode(err.code), { cause: err });
}
