import "server-only";
import { z } from "zod";
import { TranscriptProviderNameSchema } from "@/lib/wire/ingest";
import type { DocumentStore } from "../../state";
import { TRANSCRIPT_CACHE_MAX_BYTES, TRANSCRIPT_CACHE_TTL_MS } from "./limits";
import type { Transcript } from "./provider";
import type { TranscriptProviderName } from "@/lib/wire/ingest";

/** What is cached: what a provider returned, and which one it was. */
export type CachedTranscript = {
  transcript: Transcript;
  provider: TranscriptProviderName;
};

// The store hands back untyped JSON, so check it before trusting it.
const CachedSchema = z.object({
  provider: TranscriptProviderNameSchema,
  transcript: z.object({
    title: z.string(),
    channel: z.string(),
    durationSec: z.number(),
    language: z.string(),
    isAutoGenerated: z.boolean().nullable(),
    segments: z.array(
      z.object({
        startMs: z.number(),
        durMs: z.number(),
        text: z.string(),
      }),
    ),
  }),
});

/**
 * Keyed by video and the base language asked for. `pt-BR` and `pt` share an
 * entry: the track picker treats them as the same preference anyway.
 */
export function cacheKey(videoId: string, preferredLang: string): string {
  const base = preferredLang.toLowerCase().split("-")[0] || "en";
  return `yt:${videoId}:${base}`;
}

/**
 * A cache that is down or holds junk is a miss, never an error: the worst
 * outcome is one more upstream call.
 */
export async function readCachedTranscript(
  store: DocumentStore,
  videoId: string,
  preferredLang: string,
): Promise<CachedTranscript | null> {
  try {
    const stored = await store.get(cacheKey(videoId, preferredLang));
    if (stored === null) return null;
    const parsed = CachedSchema.safeParse(stored);
    return parsed.success ? parsed.data : null;
  } catch (err) {
    console.warn("youtube cache read failed", err);
    return null;
  }
}

/** Returns false when the entry was too big to store or the store failed. */
export async function writeCachedTranscript(
  store: DocumentStore,
  videoId: string,
  preferredLang: string,
  value: CachedTranscript,
  ttlMs: number = TRANSCRIPT_CACHE_TTL_MS,
): Promise<boolean> {
  // Upstash rejects large requests; a 6-hour talk should still ingest, just
  // without being cached.
  if (
    Buffer.byteLength(JSON.stringify(value), "utf8") >
    TRANSCRIPT_CACHE_MAX_BYTES
  ) {
    return false;
  }
  try {
    await store.put(cacheKey(videoId, preferredLang), value, ttlMs);
    return true;
  } catch (err) {
    console.warn("youtube cache write failed", err);
    return false;
  }
}
