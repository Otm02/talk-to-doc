import { describe, expect, it } from "vitest";
import type { DocumentData } from "@/features/ingest/ingest-state";
import {
  buildGroups,
  groupsToPlainText,
  indexMatches,
  previewExcerpt,
  splitByQuery,
} from "./text-groups";

const pdf = (texts: string[]): DocumentData => ({
  meta: { documentId: "d", title: "T", sourceType: "pdf", pages: texts.length },
  pages: texts.map((text, i) => ({ page: i + 1, text })),
  segments: [],
  done: null,
});

const video = (starts: number[]): DocumentData => ({
  meta: {
    documentId: "d",
    title: "T",
    sourceType: "youtube",
    videoId: "jNQXAC9IVRw",
    thumbnailUrl: "x",
    channel: "c",
    durationSec: 900,
    language: "en",
    isAutoGenerated: false,
    provider: "direct",
    cached: false,
  },
  pages: [],
  segments: starts.map((startSec) => ({ startSec, text: `at ${startSec}` })),
  done: null,
});

describe("buildGroups", () => {
  it("groups a PDF by page", () => {
    const g = buildGroups(pdf(["a", "b"]));
    expect(g.map((x) => x.label)).toEqual(["Page 1", "Page 2"]);
  });

  it("groups a video by 5-minute block with a YouTube link per line", () => {
    const g = buildGroups(video([0, 30, 299, 300, 650]));
    expect(g.map((x) => x.units.length)).toEqual([3, 1, 1]);
    expect(g[0]?.label).toBe("00:00 – 05:00");
    expect(g[2]?.units[0]?.stamp).toEqual({
      label: "10:50",
      href: "https://www.youtube.com/watch?v=jNQXAC9IVRw&t=650s",
    });
  });
});

describe("groupsToPlainText", () => {
  it("uses page markers for PDFs and timestamps for video", () => {
    expect(groupsToPlainText(buildGroups(pdf(["a"])))).toBe("[Page 1]\na");
    expect(groupsToPlainText(buildGroups(video([5])))).toBe("[00:05] at 5");
  });
});

describe("previewExcerpt", () => {
  it("returns short text whole", () => {
    expect(previewExcerpt(buildGroups(pdf(["short"])))).toBe("short");
  });
  it("cuts long text near the limit at a word edge", () => {
    const out = previewExcerpt(buildGroups(pdf(["word ".repeat(400)])), 600);
    expect(out.endsWith("…")).toBe(true);
    expect(out.length).toBeLessThanOrEqual(601);
    expect(out).not.toMatch(/wor…$/);
  });
});

describe("search", () => {
  it("splits around matches, case-insensitively, without HTML", () => {
    expect(splitByQuery("A <b>a</b>", "a")).toEqual([
      { text: "A", match: true },
      { text: " <b>", match: false },
      { text: "a", match: true },
      { text: "</b>", match: false },
    ]);
    expect(splitByQuery("x", "").every((p) => !p.match)).toBe(true);
  });

  it("counts matches across groups and maps them to groups", () => {
    const idx = indexMatches(buildGroups(pdf(["foo foo", "bar", "Foo"])), "foo");
    expect(idx.total).toBe(3);
    expect(idx.groupOfMatch).toEqual([0, 0, 2]);
  });
});
