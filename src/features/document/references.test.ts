import { describe, expect, it } from "vitest";
import type { DocumentData } from "@/features/ingest/ingest-state";
import {
  buildReferenceIndex,
  parseReferences,
  type ReferencePart,
} from "./references";
import { buildGroups } from "./text-groups";

function pdf(pages: number): DocumentData {
  return {
    meta: { documentId: "d", title: "Report", sourceType: "pdf", pages },
    pages: Array.from({ length: pages }, (_, i) => ({
      page: i + 1,
      text: `Text of page ${i + 1}.`,
    })),
    segments: [],
    done: null,
  };
}

function video(starts: number[], durationSec: number): DocumentData {
  return {
    meta: {
      documentId: "v",
      title: "Talk",
      sourceType: "youtube",
      videoId: "dQw4w9WgXcQ",
      thumbnailUrl: "https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg",
      channel: "Channel",
      durationSec,
      language: "en",
      isAutoGenerated: false,
      provider: "direct",
      cached: false,
    },
    pages: [],
    segments: starts.map((startSec) => ({ startSec, text: `At ${startSec}.` })),
    done: null,
  };
}

const pdfIndex = (pages = 12) => buildReferenceIndex(buildGroups(pdf(pages)));
// Paragraphs every 30 s for 1 h 10 min: blocks b0 to b13.
const VIDEO = video(
  Array.from({ length: 140 }, (_, i) => i * 30),
  4200,
);
const videoIndex = () =>
  buildReferenceIndex(
    buildGroups(VIDEO),
    VIDEO.meta.sourceType === "youtube" ? 4200 : 0,
  );

const refs = (parts: ReferencePart[]) =>
  parts.flatMap((p) => (p.kind === "ref" ? [p] : []));
const chips = (parts: ReferencePart[]) => refs(parts).map((p) => p.text);
/** Whatever the parser does, the words on screen must be the words given. */
const joined = (parts: ReferencePart[]) => parts.map((p) => p.text).join("");

describe("parseReferences: pages", () => {
  it.each([
    ["Revenue is on page 12.", "page 12", "p12"],
    ["Page 2 covers it.", "Page 2", "p2"],
    ["See p. 7 for details.", "p. 7", "p7"],
    ["See p.7 for details.", "p.7", "p7"],
    ["It runs over pages 3 to 4.", "pages 3 to 4", "p3"],
    ["It runs over pages 3-4.", "pages 3-4", "p3"],
    ["It runs over pages 3–4.", "pages 3–4", "p3"],
    ["It runs over pages 3 and 4.", "pages 3 and 4", "p3"],
    ["It runs over pages 3 through 5.", "pages 3 through 5", "p3"],
    ["Compare pp. 10-12.", "pp. 10-12", "p10"],
    ["PAGES 1 TO 2", "PAGES 1 TO 2", "p1"],
  ])("%s", (text, chip, groupId) => {
    const parts = parseReferences(text, pdfIndex());
    expect(chips(parts)).toEqual([chip]);
    expect(refs(parts)[0]?.target).toEqual({ groupId });
    expect(joined(parts)).toBe(text);
  });

  it("splits the text around several references, in order", () => {
    const text =
      "Revenue is on page 2, and the outlook is on pages 3 to 4. Page 40 is not in this report.";
    expect(parseReferences(text, pdfIndex())).toEqual([
      { kind: "text", text: "Revenue is on " },
      {
        kind: "ref",
        text: "page 2",
        label: "page 2",
        target: { groupId: "p2" },
      },
      { kind: "text", text: ", and the outlook is on " },
      {
        kind: "ref",
        text: "pages 3 to 4",
        label: "page 3",
        target: { groupId: "p3" },
      },
      { kind: "text", text: ". Page 40 is not in this report." },
    ]);
  });

  it.each([
    "See page 13.", // one past the end
    "See page 0.",
    "See page 40.",
    "See pages 11 to 13.", // range runs off the end
    "See pages 5 to 3.", // backwards
    "See p. 99.",
  ])("ignores a target that is not in the document: %s", (text) => {
    const parts = parseReferences(text, pdfIndex());
    expect(chips(parts)).toEqual([]);
    expect(parts).toEqual([{ kind: "text", text }]);
  });

  it("does not read numbers that are not page references", () => {
    for (const text of [
      "There are 12 pages in total.",
      "The 3-page summary is short.",
      "It grew 12 percent.",
      "See the homepage 3 times.", // "page" inside another word
      "stop. 7 people came", // "p." inside another word
      "page twelve",
      "page 12th", // not a clean number
    ]) {
      expect(chips(parseReferences(text, pdfIndex()))).toEqual([]);
    }
  });

  it("keeps a singular 'page' to one page, even when a number follows", () => {
    const parts = parseReferences("On page 3 and 4 people agreed.", pdfIndex());
    expect(chips(parts)).toEqual(["page 3"]);
  });

  it("links the valid reference and leaves the invalid one next to it", () => {
    const parts = parseReferences("Compare page 2 with page 99.", pdfIndex());
    expect(chips(parts)).toEqual(["page 2"]);
    expect(joined(parts)).toBe("Compare page 2 with page 99.");
  });

  it("only knows pages that were actually extracted", () => {
    // Still streaming in: the document says 12 pages, 2 have arrived.
    const doc = pdf(12);
    doc.pages = doc.pages.slice(0, 2);
    const index = buildReferenceIndex(buildGroups(doc));
    expect(chips(parseReferences("page 2, page 3", index))).toEqual(["page 2"]);
  });
});

describe("parseReferences: timestamps", () => {
  it("links [mm:ss] to the paragraph being spoken at that second", () => {
    const text = "He explains it at [04:05].";
    const parts = parseReferences(text, videoIndex());
    expect(parts).toEqual([
      { kind: "text", text: "He explains it at " },
      {
        kind: "ref",
        text: "[04:05]",
        label: "04:05",
        // 245 s: the paragraph that started at 240 s (s8), in block 0 to 5 min.
        target: { groupId: "b0", unitId: "s8" },
      },
      { kind: "text", text: "." },
    ]);
  });

  it("links [h:mm:ss]", () => {
    const parts = parseReferences("Near the end, [1:04:05].", videoIndex());
    expect(chips(parts)).toEqual(["[1:04:05]"]);
    // 3845 s: paragraph 128 (3840 s), block 12 (1:00:00 to 1:05:00).
    expect(refs(parts)[0]?.target).toEqual({ groupId: "b12", unitId: "s128" });
    expect(refs(parts)[0]?.label).toBe("1:04:05");
  });

  it.each([
    ["[00:00]", "s0"],
    ["[0:30]", "s1"],
    ["[05:00]", "s10"],
    ["[69:30]", "s139"], // minutes past 59 are fine without an hours part
    ["[1:10:00]", "s139"], // the very end of the video
  ])("resolves %s to %s", (stamp, unitId) => {
    const parts = parseReferences(`at ${stamp}`, videoIndex());
    expect(refs(parts)[0]?.target.unitId).toBe(unitId);
  });

  it.each([
    "[1:10:01]", // one second past the end
    "[99:00]",
    "[2:00:00]",
    "[04:75]", // not a time
    "[1:75:00]", // not a time
    "04:05", // no brackets: could be anything
    "[4]",
    "[a:bc]",
  ])("ignores %s", (stamp) => {
    const text = `Look at ${stamp} please.`;
    expect(parseReferences(text, videoIndex())).toEqual([
      { kind: "text", text },
    ]);
  });

  it("uses the first paragraph for a time before the captions start", () => {
    const late = video([12, 40], 60);
    const index = buildReferenceIndex(buildGroups(late), 60);
    const parts = parseReferences("[00:03]", index);
    expect(refs(parts)[0]?.target).toEqual({ groupId: "b0", unitId: "s0" });
  });

  it("without a known duration, the last paragraph's start is the limit", () => {
    const index = buildReferenceIndex(buildGroups(video([0, 30, 60], 0)));
    expect(chips(parseReferences("[01:00] [01:01]", index))).toEqual([
      "[01:00]",
    ]);
  });
});

describe("parseReferences: the right kind for the right source", () => {
  it("makes no page chips in a video and no time chips in a PDF", () => {
    expect(chips(parseReferences("page 2 at [00:30]", videoIndex()))).toEqual([
      "[00:30]",
    ]);
    expect(chips(parseReferences("page 2 at [00:30]", pdfIndex()))).toEqual([
      "page 2",
    ]);
  });

  it("makes nothing for a document with no text yet", () => {
    const empty = buildReferenceIndex([]);
    expect(parseReferences("page 1 [00:01]", empty)).toEqual([
      { kind: "text", text: "page 1 [00:01]" },
    ]);
  });
});

describe("parseReferences: any reply language", () => {
  it("finds the references in a French reply", () => {
    const text =
      "Le chiffre d'affaires est détaillé à la page 12, et les perspectives aux pages 3 à 4 (voir aussi p. 7 et les pages 9 et 10).";
    const parts = parseReferences(text, pdfIndex());
    expect(chips(parts)).toEqual([
      "page 12",
      "pages 3 à 4",
      "p. 7",
      "pages 9 et 10",
    ]);
    expect(refs(parts).map((p) => p.target.groupId)).toEqual([
      "p12",
      "p3",
      "p7",
      "p9",
    ]);
    expect(joined(parts)).toBe(text);
  });

  it("finds timestamps in a French reply about a video", () => {
    const text = "Il en parle vers [04:05], puis y revient à [1:04:05].";
    expect(chips(parseReferences(text, videoIndex()))).toEqual([
      "[04:05]",
      "[1:04:05]",
    ]);
  });

  it("leaves accented text and punctuation exactly as written", () => {
    const text = "Très bien — voilà : « page 2 ».";
    const parts = parseReferences(text, pdfIndex());
    expect(joined(parts)).toBe(text);
    expect(chips(parts)).toEqual(["page 2"]);
  });
});

describe("parseReferences: streaming and edges", () => {
  it("returns nothing for empty text and one text part when there is no reference", () => {
    expect(parseReferences("", pdfIndex())).toEqual([]);
    expect(parseReferences("Nothing here.", pdfIndex())).toEqual([
      { kind: "text", text: "Nothing here." },
    ]);
  });

  it("only links a reference once it has fully arrived", () => {
    const index = videoIndex();
    for (const partial of [
      "See [",
      "See [04",
      "See [04:",
      "See [04:0",
      "See [04:05",
    ]) {
      expect(chips(parseReferences(partial, index))).toEqual([]);
    }
    expect(chips(parseReferences("See [04:05]", index))).toEqual(["[04:05]"]);
  });

  it("handles a reference at the very start and the very end", () => {
    expect(parseReferences("page 1", pdfIndex())).toEqual([
      {
        kind: "ref",
        text: "page 1",
        label: "page 1",
        target: { groupId: "p1" },
      },
    ]);
  });

  it("gives the same answer when called twice (no regex state leaks)", () => {
    const index = pdfIndex();
    const text = "page 1 and page 2";
    expect(parseReferences(text, index)).toEqual(parseReferences(text, index));
    expect(chips(parseReferences(text, index))).toEqual(["page 1", "page 2"]);
  });
});
