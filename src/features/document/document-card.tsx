import { FileText, Info, CirclePlay } from "lucide-react";
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover";
import type { DocumentData } from "@/features/ingest/ingest-state";
import { coverageLine, formatCount, formatDuration } from "./format";

/** Pages with no text are usually images; worth telling the user. */
function emptyPageCount(doc: DocumentData): number {
  return doc.pages.filter((p) => p.text.trim() === "").length;
}

export function DocumentCard({ doc }: { doc: DocumentData }) {
  const { meta, done } = doc;
  const isVideo = meta.sourceType === "youtube";
  const Icon = isVideo ? CirclePlay : FileText;
  const words = done?.stats.words;
  const tokens = done?.stats.tokens;
  const size = isVideo
    ? formatDuration(meta.durationSec)
    : `${meta.pages} ${meta.pages === 1 ? "page" : "pages"}`;
  const empty = !isVideo && done ? emptyPageCount(doc) : 0;

  return (
    <section
      aria-label="Document"
      className="flex flex-col gap-3 rounded-xl border bg-card p-4 text-card-foreground"
    >
      {isVideo && (
        // A plain img: a 480x360 CDN thumbnail, already allowed by the CSP.
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={meta.thumbnailUrl}
          alt=""
          width={480}
          height={360}
          className="aspect-video w-full rounded-lg bg-muted object-cover"
        />
      )}
      <div className="flex items-start gap-3">
        <Icon aria-hidden className="mt-0.5 size-5 shrink-0 text-muted-foreground" />
        <div className="min-w-0 flex-1">
          <h2 className="text-base leading-snug font-semibold break-words">
            {meta.title}
          </h2>
          {isVideo && meta.channel && (
            <p className="text-sm text-muted-foreground">{meta.channel}</p>
          )}
        </div>
      </div>

      <p className="text-sm text-muted-foreground">
        {size}
        {words !== undefined && tokens !== undefined
          ? ` · ${formatCount(words)} words · ${formatCount(tokens)} tokens`
          : " · Counting…"}
      </p>

      {isVideo && meta.isAutoGenerated === true && (
        <p className="w-fit rounded-full bg-secondary px-2.5 py-1 text-xs font-medium text-secondary-foreground">
          Auto-generated captions
        </p>
      )}

      {done && (
        <div className="flex items-center gap-1 text-sm">
          <span>{coverageLine(done.coverage)}</span>
          <Popover>
            <PopoverTrigger
              aria-label="Why this matters"
              className="inline-flex size-11 items-center justify-center rounded-full outline-none focus-visible:ring-3 focus-visible:ring-ring/50"
            >
              <Info aria-hidden className="size-4" />
            </PopoverTrigger>
            <PopoverContent className="text-sm">
              The voice assistant can only keep a limited amount of text in mind
              at once. It reads from the start, so anything past that point
              isn&rsquo;t available to it. The preview below always shows the
              full text.
            </PopoverContent>
          </Popover>
        </div>
      )}

      {empty > 0 && (
        <p className="text-sm text-muted-foreground">
          {empty} {empty === 1 ? "page" : "pages"} had no text (they may be
          images).
        </p>
      )}
    </section>
  );
}
