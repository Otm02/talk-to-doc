// @vitest-environment jsdom
import { act, renderHook } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  isOffline,
  markUnreachable,
  resetConnectivityForTests,
} from "@/lib/net/connectivity";
import { encodeNdjsonLine } from "@/lib/wire/ndjson";
import { IngestError } from "./ingest-error";
import { UPLOAD_STALL_MS, useIngest } from "./use-ingest";
import * as client from "./upload-client";

vi.mock("./upload-client", () => ({
  getUploadMode: vi.fn(),
  ingestPdf: vi.fn(),
  ingestYoutube: vi.fn(),
}));

const getUploadMode = vi.mocked(client.getUploadMode);
const ingestPdf = vi.mocked(client.ingestPdf);
const ingestYoutube = vi.mocked(client.ingestYoutube);

const video = {
  documentId: "d",
  title: "T",
  sourceType: "youtube",
  videoId: "jNQXAC9IVRw",
  thumbnailUrl: "https://i.ytimg.com/x.jpg",
  channel: "c",
  durationSec: 600,
  language: "en",
  isAutoGenerated: false,
  provider: "direct",
  cached: false,
};
const pdfMeta = { documentId: "d", title: "T", sourceType: "pdf", pages: 3 };
const done = {
  done: true,
  stats: { segments: 1, words: 2, tokens: 3 },
  coverage: 1,
};

function streamOf(...lines: unknown[]): ReadableStream<Uint8Array> {
  const bytes = new TextEncoder().encode(lines.map(encodeNdjsonLine).join(""));
  return new ReadableStream({
    start(c) {
      c.enqueue(bytes);
      c.close();
    },
  });
}

const goodVideo = () =>
  streamOf(video, { segment: { startSec: 0, text: "hello" } }, done);
/** Starts a document and then just ends: no `done`. */
const cutVideo = () =>
  streamOf(video, { segment: { startSec: 0, text: "hel" } });
const cutPdf = () =>
  streamOf(pdfMeta, { page: 1, text: "a" }, { page: 2, text: "b" });

const pdfFile = () =>
  new File([new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2d, 0x31])], "a.pdf", {
    type: "application/pdf",
  });

function setOnLine(value: boolean) {
  Object.defineProperty(navigator, "onLine", { configurable: true, value });
}

/** Lets promise callbacks, then timers up to `ms`, run. */
const flush = (ms = 100) => act(() => vi.advanceTimersByTimeAsync(ms));

beforeEach(() => {
  vi.useFakeTimers();
  setOnLine(true);
  resetConnectivityForTests();
  getUploadMode.mockResolvedValue("direct");
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue(new Response("{}")));
});
afterEach(() => {
  vi.useRealTimers();
  vi.unstubAllGlobals();
  vi.resetAllMocks();
});

describe("a YouTube stream that breaks", () => {
  it("is asked for again once, silently, and then succeeds", async () => {
    ingestYoutube
      .mockResolvedValueOnce(cutVideo())
      .mockResolvedValueOnce(goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state.status).toBe("ready");
  });

  it("keeps what arrived and offers a retry when the second try breaks too", async () => {
    ingestYoutube.mockImplementation(async () => cutVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    const { state } = result.current;
    expect(state.status).toBe("partial");
    expect(state.status === "partial" && state.doc.segments).toHaveLength(1);

    // The user's own Try again gets a fresh silent retry.
    ingestYoutube.mockImplementation(async () => goodVideo());
    act(() => result.current.retry());
    await flush();
    expect(result.current.state.status).toBe("ready");
  });

  it("does not loop: one silent retry per tap", async () => {
    ingestYoutube.mockImplementation(async () => cutVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush(10_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
  });
});

describe("a PDF stream that breaks", () => {
  it("shows the pages it has, with no automatic retry (the file is consumed)", async () => {
    ingestPdf.mockResolvedValue(cutPdf());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    await flush();
    expect(ingestPdf).toHaveBeenCalledTimes(1);
    const { state } = result.current;
    expect(state.status).toBe("partial");
    expect(state.status === "partial" && state.doc.pages).toHaveLength(2);
    // The server answered; a dropped stream is not "offline".
    expect(isOffline()).toBe(false);
  });
});

describe("a call that got no answer", () => {
  const noAnswer = () =>
    new IngestError("youtube_failed", "Failed to fetch", undefined, true);

  it("shows the error, waits for the connection, and then goes again by itself", async () => {
    ingestYoutube
      .mockRejectedValueOnce(noAnswer())
      .mockResolvedValueOnce(goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    // Offline is said as offline, not as "couldn't load this video's captions".
    expect(result.current.state).toMatchObject({
      status: "error",
      code: "network_failed",
    });
    expect(isOffline()).toBe(true);
    expect(ingestYoutube).toHaveBeenCalledTimes(1);

    // The health probe finds the server again.
    await flush(2_500);
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state.status).toBe("ready");
    expect(isOffline()).toBe(false);
  });

  it("resumes the moment the browser says it is online", async () => {
    setOnLine(false);
    ingestYoutube
      .mockRejectedValueOnce(noAnswer())
      .mockResolvedValueOnce(goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush(10_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(1);

    setOnLine(true);
    act(() => void window.dispatchEvent(new Event("online")));
    await flush();
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state.status).toBe("ready");
  });

  it("resumes only once, so a dead server cannot make a loop", async () => {
    ingestYoutube.mockImplementation(async () => {
      throw noAnswer();
    });
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush(60_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state.status).toBe("error");
  });

  it("does not wait for a refusal: the server answered", async () => {
    ingestYoutube.mockRejectedValue(
      new IngestError("youtube_no_transcript", "HTTP 422"),
    );
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush(60_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(1);
    expect(isOffline()).toBe(false);
  });

  it("Cancel while waiting stops the wait for good", async () => {
    ingestYoutube.mockRejectedValue(noAnswer());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    act(() => result.current.reset());
    await flush(60_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(1);
    expect(result.current.state.status).toBe("idle");
  });

  it("a new tap while waiting replaces the pending resume", async () => {
    ingestYoutube
      .mockRejectedValueOnce(noAnswer())
      .mockResolvedValueOnce(goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    act(() => result.current.retry());
    await flush(60_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state.status).toBe("ready");
  });
});

describe("an upload that stops moving", () => {
  /** An upload that reports `first`, then hangs. Returns the progress callback. */
  function hangingUpload(first: number) {
    const callbacks: { progress: (n: number) => void } = { progress: () => {} };
    ingestPdf.mockImplementation((_file, _mode, _signal, cb) => {
      callbacks.progress = (n) => cb?.onUploadProgress?.(n);
      cb?.onUploadProgress?.(first);
      return new Promise(() => {});
    });
    return callbacks;
  }

  const stalled = (r: { current: ReturnType<typeof useIngest> }) =>
    r.current.state.status === "uploading" && r.current.state.stalled;

  it("says so after 20 s with no progress, and never before", async () => {
    hangingUpload(10);
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    await flush(UPLOAD_STALL_MS - 2_000);
    expect(stalled(result)).toBe(false);
    await flush(3_000);
    expect(stalled(result)).toBe(true);
    // The percent shown is still the one that was really reported.
    expect(result.current.state).toMatchObject({ percent: 10 });
  });

  it("Keep waiting clears it, and it comes back after another 20 s of silence", async () => {
    hangingUpload(10);
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    // Reading the file's first bytes takes a real moment; let it finish first
    // so the stall clock has fake time left to tick in.
    await vi.waitFor(() =>
      expect(result.current.state.status).toBe("uploading"),
    );
    await flush(UPLOAD_STALL_MS + 2_000);
    expect(stalled(result)).toBe(true);

    act(() => result.current.keepWaiting());
    expect(stalled(result)).toBe(false);
    await flush(UPLOAD_STALL_MS - 2_000);
    expect(stalled(result)).toBe(false);
    await flush(3_000);
    expect(stalled(result)).toBe(true);
  });

  it("any progress clears it and restarts the clock", async () => {
    const upload = hangingUpload(10);
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    // Reading the file's first bytes takes a real moment; let it finish first
    // so the stall clock has fake time left to tick in.
    await vi.waitFor(() =>
      expect(result.current.state.status).toBe("uploading"),
    );
    await flush(UPLOAD_STALL_MS + 2_000);
    expect(stalled(result)).toBe(true);

    act(() => upload.progress(11));
    expect(stalled(result)).toBe(false);
    expect(result.current.state).toMatchObject({ percent: 11 });
    await flush(UPLOAD_STALL_MS - 2_000);
    expect(stalled(result)).toBe(false);
  });

  it("Cancel from the slow state goes back to the start", async () => {
    hangingUpload(10);
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    // Reading the file's first bytes takes a real moment; let it finish first
    // so the stall clock has fake time left to tick in.
    await vi.waitFor(() =>
      expect(result.current.state.status).toBe("uploading"),
    );
    await flush(UPLOAD_STALL_MS + 2_000);
    act(() => result.current.cancel());
    await flush();
    expect(result.current.state.status).toBe("idle");
  });

  it("is not checked once the file is up and the server is reading", async () => {
    ingestPdf.mockImplementation((_file, _mode, _signal, cb) => {
      cb?.onUploadProgress?.(100);
      cb?.onUploaded?.();
      return new Promise(() => {});
    });
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startPdf(pdfFile()));
    await flush(UPLOAD_STALL_MS * 3);
    expect(result.current.state.status).toBe("extracting");
  });
});

describe("leaving the screen", () => {
  it("aborts the request in flight", async () => {
    let seen: AbortSignal | undefined;
    ingestYoutube.mockImplementation((_url, signal) => {
      seen = signal;
      return new Promise(() => {});
    });
    const { result, unmount } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    expect(seen?.aborted).toBe(false);
    unmount();
    expect(seen?.aborted).toBe(true);
  });

  it("drops a pending resume and the stall check", async () => {
    ingestYoutube.mockRejectedValue(
      new IngestError("youtube_failed", "x", undefined, true),
    );
    const { result, unmount } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    unmount();
    markUnreachable();
    act(() => void window.dispatchEvent(new Event("online")));
    await flush(60_000);
    expect(ingestYoutube).toHaveBeenCalledTimes(1);
    expect(vi.getTimerCount()).toBe(0);
  });
});

describe("cancelling", () => {
  it("is not undone by the cancelled load's late failure", async () => {
    let rejectFirst: (e: unknown) => void = () => {};
    ingestYoutube
      .mockImplementationOnce(
        () => new Promise((_, reject) => (rejectFirst = reject)),
      )
      .mockImplementationOnce(() => new Promise(() => {}));
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/a"));
    await flush();
    act(() => result.current.cancel());
    expect(result.current.state.status).toBe("idle");

    // A new load starts, then the old one finally fails.
    act(() => void result.current.startYoutube("https://youtu.be/b"));
    await flush();
    expect(result.current.state.status).toBe("extracting");
    rejectFirst(new DOMException("Aborted", "AbortError"));
    await flush();
    expect(result.current.state.status).toBe("extracting");
  });
});

describe("stallThresholdMs", () => {
  it("is 20 seconds, and a test flag can shorten it in a dev or mock build", async () => {
    const { stallThresholdMs } = await import("./use-ingest");
    expect(stallThresholdMs("")).toBe(UPLOAD_STALL_MS);
    expect(stallThresholdMs("?mockStallMs=1500")).toBe(1500);
    expect(stallThresholdMs("?mockStallMs=-3")).toBe(UPLOAD_STALL_MS);
    expect(stallThresholdMs("?mockStallMs=abc")).toBe(UPLOAD_STALL_MS);
  });
});

describe("Load it again from a document that is already on screen", () => {
  it("shows the load as working, instead of leaving the old document and its buttons live", async () => {
    ingestYoutube.mockImplementationOnce(async () => goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    expect(result.current.state.status).toBe("ready");

    // The document expired on the server; the screen loads the same link again.
    ingestYoutube.mockImplementationOnce(() => new Promise(() => {}));
    act(() => result.current.retry());
    await flush();
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
    expect(result.current.state).toEqual({ status: "extracting", doc: null });
  });

  it("and lands on the new document when it arrives", async () => {
    ingestYoutube
      .mockImplementationOnce(async () => goodVideo())
      .mockImplementationOnce(async () => goodVideo());
    const { result } = renderHook(() => useIngest());
    act(() => void result.current.startYoutube("https://youtu.be/x"));
    await flush();
    act(() => result.current.retry());
    await flush();
    expect(result.current.state.status).toBe("ready");
    expect(ingestYoutube).toHaveBeenCalledTimes(2);
  });
});

describe("a file that is not a PDF at all", () => {
  it("is refused before any upload token is asked for", async () => {
    const { result } = renderHook(() => useIngest());
    // Named .pdf, typed as a PDF, but the bytes are a PNG.
    const fake = new File([new Uint8Array([0x89, 0x50, 0x4e, 0x47])], "a.pdf", {
      type: "application/pdf",
    });
    act(() => void result.current.startPdf(fake));
    await flush();
    expect(result.current.state).toMatchObject({
      status: "error",
      code: "pdf_not_pdf",
    });
    expect(getUploadMode).not.toHaveBeenCalled();
    expect(ingestPdf).not.toHaveBeenCalled();
  });

  it("lets a real header through, even with a few bytes of junk before it", async () => {
    ingestPdf.mockResolvedValue(streamOf(pdfMeta, { page: 1, text: "a" }));
    const { result } = renderHook(() => useIngest());
    const junk = new TextEncoder().encode("\n\n  %PDF-1.7\n");
    act(
      () =>
        void result.current.startPdf(
          new File([junk], "a.pdf", { type: "application/pdf" }),
        ),
    );
    await flush();
    expect(ingestPdf).toHaveBeenCalledTimes(1);
  });
});
