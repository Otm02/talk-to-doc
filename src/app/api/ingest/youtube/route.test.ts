import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { stubYoutube, type Routes } from "@test/youtubeFetch";
import { ERROR_CATALOG } from "@/lib/errors/catalog";
import { IngestLineSchema, type IngestLine } from "@/lib/wire/ingest";
import { readNdjson } from "@/lib/wire/ndjson";
import { resetEnvCacheForTests } from "@/server/env";
import type { YoutubeDocumentRecord } from "@/server/ingest/record";
import type { StateAdapters } from "@/server/state";
import { createMemoryAdapters } from "@/server/state/memory";

const holder = vi.hoisted(() => ({
  state: undefined as StateAdapters | undefined,
}));
vi.mock("@/server/state", () => ({
  getState: () => {
    if (!holder.state) throw new Error("test state not set");
    return holder.state;
  },
}));

import { POST, maxDuration } from "./route";

const IP = { "x-forwarded-for": "203.0.113.5" };

const post = (body: unknown) =>
  POST(
    new Request("http://localhost/api/ingest/youtube", {
      method: "POST",
      headers: IP,
      body: JSON.stringify(body),
    }),
  );

async function readLines(res: Response): Promise<IngestLine[]> {
  if (!res.body) throw new Error("no body");
  const out: IngestLine[] = [];
  for await (const line of readNdjson(res.body, IngestLineSchema))
    out.push(line);
  return out;
}

async function expectError(res: Response, code: keyof typeof ERROR_CATALOG) {
  expect(res.status).toBe(ERROR_CATALOG[code].status);
  expect(res.headers.get("content-type")).toContain("application/json");
  const body = await res.json();
  expect(body.error).toEqual({ code, message: ERROR_CATALOG[code].message });
  expect(typeof body.requestId).toBe("string");
}

const MANUAL = "https://www.youtube.com/watch?v=jNQXAC9IVRw";

beforeEach(() => {
  holder.state = createMemoryAdapters();
  // These tests exercise Direct alone, whatever is in the developer's .env.local.
  vi.stubEnv("SUPADATA_API_KEY", "");
  vi.stubEnv("VERCEL", "");
  vi.stubEnv("VERCEL_ENV", "");
  resetEnvCacheForTests();
  vi.spyOn(console, "error").mockImplementation(() => undefined);
  vi.spyOn(console, "info").mockImplementation(() => undefined);
});
afterEach(() => {
  vi.unstubAllEnvs();
  vi.unstubAllGlobals();
  resetEnvCacheForTests();
  vi.restoreAllMocks();
});

describe("POST /api/ingest/youtube (Direct, recorded responses)", () => {
  it("streams a captioned video end to end", async () => {
    stubYoutube("manual");
    const res = await post({ url: MANUAL });

    expect(res.status).toBe(200);
    expect(res.headers.get("content-type")).toBe(
      "application/x-ndjson; charset=utf-8",
    );
    expect(res.headers.get("x-request-id")).toBeTruthy();

    const lines = await readLines(res);
    expect(lines[0]).toMatchObject({
      sourceType: "youtube",
      videoId: "jNQXAC9IVRw",
      title: "Me at the zoo",
      channel: "jawed",
      durationSec: 19,
      language: "en",
      isAutoGenerated: false,
      provider: "direct",
      cached: false,
      thumbnailUrl: "https://i.ytimg.com/vi/jNQXAC9IVRw/hqdefault.jpg",
    });
    expect(lines.at(-1)).toMatchObject({ done: true, coverage: 1 });

    const first = lines[1];
    expect(first && "segment" in first && first.segment.startSec).toBe(1);
    expect(first && "segment" in first && first.segment.text).toContain(
      "All right, so here we are",
    );
  });

  it("stores the model's context with timestamps", async () => {
    stubYoutube("manual");
    const [meta] = await readLines(await post({ url: MANUAL }));
    if (!meta || !("documentId" in meta)) throw new Error("no meta");
    const record = (await holder.state?.documents.get(
      meta.documentId,
    )) as YoutubeDocumentRecord | null;
    expect(record?.context).toMatch(/^\[00:01\] All right, so here we are/);
  });

  it("serves a Short and a youtu.be link through the same path", async () => {
    stubYoutube("manual");
    for (const url of [
      "https://www.youtube.com/shorts/jNQXAC9IVRw",
      "https://youtu.be/jNQXAC9IVRw?si=abc",
    ]) {
      const [meta] = await readLines(await post({ url }));
      expect(meta).toMatchObject({
        videoId: "jNQXAC9IVRw",
        provider: "direct",
      });
    }
  });

  it("asks for the requested language", async () => {
    stubYoutube("manual");
    const [meta] = await readLines(await post({ url: MANUAL, lang: "de" }));
    expect(meta).toMatchObject({ language: "de" });
  });

  it("flags auto-generated captions", async () => {
    stubYoutube("auto-only");
    const [meta] = await readLines(
      await post({ url: "https://youtu.be/_OBlgSz8sSM" }),
    );
    expect(meta).toMatchObject({ isAutoGenerated: true, language: "en" });
  });

  it("asks YouTube once for the same video within the hour", async () => {
    const { fetchMock } = stubYoutube("manual");
    const first = await readLines(await post({ url: MANUAL }));
    const callsAfterFirst = fetchMock.mock.calls.length;
    const second = await readLines(await post({ url: MANUAL }));

    expect(fetchMock.mock.calls.length).toBe(callsAfterFirst);
    expect(first[0]).toMatchObject({ cached: false });
    expect(second[0]).toMatchObject({ cached: true, provider: "direct" });
  });

  it("answers a captions-disabled video with friendly copy", async () => {
    stubYoutube("disabled");
    const res = await post({
      url: "https://www.youtube.com/watch?v=dMH0bHeiRNg",
    });
    await expectError(res, "youtube_no_transcript");
    expect(ERROR_CATALOG.youtube_no_transcript.message).toBe(
      "This video has no captions, so there's nothing to read. Try another video.",
    );
  });

  it("answers a removed video", async () => {
    stubYoutube("unavailable");
    await expectError(
      await post({ url: "https://www.youtube.com/watch?v=KmtzQCSh6xk" }),
      "youtube_unavailable",
    );
  });

  it("says YouTube is blocking us when Direct is blocked and nothing backs it up", async () => {
    stubYoutube("manual", { watch: () => new Response("", { status: 429 }) });
    await expectError(await post({ url: MANUAL }), "youtube_blocked");
  });

  it("rejects a bad link without touching the network", async () => {
    const { fetchMock } = stubYoutube("manual");
    await expectError(
      await post({ url: "https://evil.com/x" }),
      "youtube_bad_url",
    );
    await expectError(
      await post({ url: "https://www.youtube.com/playlist?list=PL1" }),
      "youtube_no_video_id",
    );
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("exports a 60 s budget and no runtime or dynamic flag", async () => {
    expect(maxDuration).toBe(60);
    const exported = await import("./route");
    expect(Object.keys(exported).sort()).toEqual(["POST", "maxDuration"]);
  });
});

describe("POST /api/ingest/youtube (Direct blocked, Supadata behind it)", () => {
  /** YouTube answers like a cloud IP would (429); Supadata serves the talk. */
  function blockedYoutubeWithSupadata(supadata: () => Response) {
    vi.stubEnv("SUPADATA_API_KEY", "sd_test_key");
    resetEnvCacheForTests();
    const blocked: Routes = { watch: () => new Response("", { status: 429 }) };
    const youtube = stubYoutube("manual", blocked);
    const supadataCalls: URL[] = [];
    vi.stubGlobal("fetch", async (input: string | URL, init?: RequestInit) => {
      const url = new URL(input.toString());
      if (url.hostname === "api.supadata.ai") {
        supadataCalls.push(url);
        return supadata();
      }
      if (url.pathname === "/oembed") {
        return Response.json({ title: "Me at the zoo", author_name: "jawed" });
      }
      return youtube.fetchMock(input, init);
    });
    return { supadataCalls };
  }

  it("falls through on a block and reports Supadata as the provider", async () => {
    const { supadataCalls } = blockedYoutubeWithSupadata(() =>
      Response.json({
        lang: "en",
        availableLangs: ["en"],
        content: [
          { text: "All right, so here we are", offset: 1200, duration: 2160 },
          { text: "in front of the elephants", offset: 5318, duration: 2656 },
        ],
      }),
    );
    const info = vi.spyOn(console, "info").mockImplementation(() => undefined);

    const lines = await readLines(await post({ url: MANUAL }));
    expect(lines[0]).toMatchObject({
      provider: "supadata",
      title: "Me at the zoo",
      channel: "jawed",
      isAutoGenerated: null,
      cached: false,
    });
    expect(supadataCalls).toHaveLength(1);
    expect(supadataCalls[0]?.searchParams.get("url")).toBe(MANUAL);

    const logged = JSON.parse(String(info.mock.calls[0]?.[0]));
    expect(logged).toMatchObject({
      provider: "supadata",
      attempts: [{ provider: "direct", code: "BLOCKED" }],
    });
    expect(JSON.stringify(logged)).not.toContain("elephants");
  });

  it("spends one Supadata credit for repeated ingests of the same video", async () => {
    const { supadataCalls } = blockedYoutubeWithSupadata(() =>
      Response.json({
        lang: "en",
        content: [{ text: "hello there", offset: 0, duration: 1000 }],
      }),
    );
    await readLines(await post({ url: MANUAL }));
    await readLines(await post({ url: MANUAL }));
    await readLines(await post({ url: "https://youtu.be/jNQXAC9IVRw" }));
    expect(supadataCalls).toHaveLength(1);
  });

  it("answers quota exhaustion with its own copy", async () => {
    blockedYoutubeWithSupadata(() => new Response("{}", { status: 429 }));
    await expectError(await post({ url: MANUAL }), "youtube_quota");
  });

  it("answers a captions-less video from Supadata (206) as no captions", async () => {
    blockedYoutubeWithSupadata(() => new Response("{}", { status: 206 }));
    await expectError(await post({ url: MANUAL }), "youtube_no_transcript");
  });
});
