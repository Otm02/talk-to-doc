import { z } from "zod";

// Shapes that cross the wire for ingestion. No `server-only` import: the
// client validates the same schemas when it reads the NDJSON stream (M4).

export const IngestStatsSchema = z.strictObject({
  pages: z.number().int().nonnegative(),
  words: z.number().int().nonnegative(),
  tokens: z.number().int().nonnegative(),
});
export type IngestStats = z.infer<typeof IngestStatsSchema>;

export const YoutubeStatsSchema = z.strictObject({
  segments: z.number().int().nonnegative(),
  words: z.number().int().nonnegative(),
  tokens: z.number().int().nonnegative(),
});
export type YoutubeStats = z.infer<typeof YoutubeStatsSchema>;

/**
 * Stream order is meta, units..., then done or error. A unit is a page for a
 * PDF and a ~30 s transcript paragraph for YouTube. Lines are told apart by
 * their keys. Stats and coverage are only known once every unit has been
 * read, so they ride on `done`: that is what lets the first unit go out in
 * milliseconds instead of after the whole file.
 */
export const PdfMetaLineSchema = z.strictObject({
  documentId: z.string().min(1),
  title: z.string(),
  sourceType: z.literal("pdf"),
  pages: z.number().int().nonnegative(),
});

export const TRANSCRIPT_PROVIDERS = ["direct", "supadata"] as const;
export const TranscriptProviderNameSchema = z.enum(TRANSCRIPT_PROVIDERS);
export type TranscriptProviderName = z.infer<
  typeof TranscriptProviderNameSchema
>;

export const YoutubeMetaLineSchema = z.strictObject({
  documentId: z.string().min(1),
  title: z.string(),
  sourceType: z.literal("youtube"),
  videoId: z.string().length(11),
  thumbnailUrl: z.string().min(1),
  channel: z.string(),
  durationSec: z.number().int().nonnegative(),
  language: z.string(),
  // null = the provider cannot tell (Supadata does not say).
  isAutoGenerated: z.boolean().nullable(),
  // Which provider served the transcript; "cached" only says it was not
  // fetched again.
  provider: TranscriptProviderNameSchema,
  cached: z.boolean(),
});

export const MetaLineSchema = z.discriminatedUnion("sourceType", [
  PdfMetaLineSchema,
  YoutubeMetaLineSchema,
]);

export const PageLineSchema = z.strictObject({
  page: z.number().int().positive(),
  text: z.string(),
});
export const SegmentLineSchema = z.strictObject({
  segment: z.strictObject({
    startSec: z.number().int().nonnegative(),
    text: z.string(),
  }),
});
export const DoneLineSchema = z.strictObject({
  done: z.literal(true),
  stats: z.union([IngestStatsSchema, YoutubeStatsSchema]),
  coverage: z.number().min(0).max(1),
});
export const ErrorLineSchema = z.strictObject({
  error: z.strictObject({ code: z.string(), message: z.string() }),
});

export const IngestLineSchema = z.union([
  MetaLineSchema,
  PageLineSchema,
  SegmentLineSchema,
  DoneLineSchema,
  ErrorLineSchema,
]);
export type PdfMetaLine = z.infer<typeof PdfMetaLineSchema>;
export type YoutubeMetaLine = z.infer<typeof YoutubeMetaLineSchema>;
export type MetaLine = z.infer<typeof MetaLineSchema>;
export type PageLine = z.infer<typeof PageLineSchema>;
export type SegmentLine = z.infer<typeof SegmentLineSchema>;
export type DoneLine = z.infer<typeof DoneLineSchema>;
export type ErrorLine = z.infer<typeof ErrorLineSchema>;
export type IngestLine = z.infer<typeof IngestLineSchema>;

/** Body of POST /api/ingest/pdf when UPLOAD_MODE=blob. */
export const BlobIngestBodySchema = z.strictObject({
  blobUrl: z.string().min(1).max(2048),
  // Only used as the title when the PDF has none; the browser knows it.
  fileName: z.string().max(255).optional(),
});
export type BlobIngestBody = z.infer<typeof BlobIngestBodySchema>;

/** Body of POST /api/ingest/youtube. */
export const YoutubeIngestBodySchema = z.strictObject({
  url: z.string().min(1).max(2048),
  // The browser's language (navigator.language). Only a preference: a video
  // without that language falls back to English, then to whatever it has.
  lang: z
    .string()
    .regex(/^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$/)
    .max(35)
    .optional(),
});
export type YoutubeIngestBody = z.infer<typeof YoutubeIngestBodySchema>;
