import { describe, expect, it } from "vitest";
import {
  IngestLineSchema,
  YoutubeIngestBodySchema,
  YoutubeMetaLineSchema,
} from "./ingest";

const youtubeMeta = {
  documentId: "doc-1",
  title: "A talk",
  sourceType: "youtube",
  videoId: "dQw4w9WgXcQ",
  thumbnailUrl: "https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg",
  channel: "Someone",
  durationSec: 213,
  language: "en",
  isAutoGenerated: null,
  provider: "supadata",
  cached: false,
} as const;

describe("ingest wire schemas", () => {
  it("still reads the PDF lines unchanged", () => {
    const lines = [
      { documentId: "d", title: "T", sourceType: "pdf", pages: 3 },
      { page: 1, text: "hello" },
      { done: true, stats: { pages: 3, words: 10, tokens: 14 }, coverage: 1 },
    ];
    for (const line of lines) {
      expect(IngestLineSchema.safeParse(line).success).toBe(true);
    }
  });

  it("reads the YouTube lines", () => {
    const lines = [
      youtubeMeta,
      { segment: { startSec: 30, text: "hello" } },
      {
        done: true,
        stats: { segments: 4, words: 40, tokens: 60 },
        coverage: 0.5,
      },
    ];
    for (const line of lines) {
      expect(IngestLineSchema.safeParse(line).success).toBe(true);
    }
  });

  it("accepts a known auto-caption flag and an unknown one", () => {
    for (const isAutoGenerated of [true, false, null]) {
      expect(
        YoutubeMetaLineSchema.safeParse({ ...youtubeMeta, isAutoGenerated })
          .success,
      ).toBe(true);
    }
  });

  it.each([
    ["an unknown provider", { provider: "scraper" }],
    ["a short video id", { videoId: "abc" }],
    ["a missing flag", { isAutoGenerated: undefined }],
    ["an extra key", { transcript: "leak" }],
  ])("rejects a YouTube meta line with %s", (_name, patch) => {
    expect(
      IngestLineSchema.safeParse({ ...youtubeMeta, ...patch }).success,
    ).toBe(false);
  });

  it("does not let a PDF meta line carry YouTube fields", () => {
    expect(
      IngestLineSchema.safeParse({
        documentId: "d",
        title: "T",
        sourceType: "pdf",
        pages: 1,
        videoId: "dQw4w9WgXcQ",
      }).success,
    ).toBe(false);
  });

  it("rejects fractional or negative segment start times", () => {
    expect(
      IngestLineSchema.safeParse({ segment: { startSec: 1.5, text: "x" } })
        .success,
    ).toBe(false);
    expect(
      IngestLineSchema.safeParse({ segment: { startSec: -1, text: "x" } })
        .success,
    ).toBe(false);
  });
});

describe("YoutubeIngestBodySchema", () => {
  it.each([
    [{ url: "https://youtu.be/dQw4w9WgXcQ" }],
    [{ url: "dQw4w9WgXcQ", lang: "en" }],
    [{ url: "dQw4w9WgXcQ", lang: "pt-BR" }],
    [{ url: "dQw4w9WgXcQ", lang: "zh-Hant-TW" }],
  ])("accepts %j", (body) => {
    expect(YoutubeIngestBodySchema.safeParse(body).success).toBe(true);
  });

  it.each([
    [{}],
    [{ url: "" }],
    [{ url: "x".repeat(2049) }],
    [{ url: "dQw4w9WgXcQ", lang: "e" }],
    [{ url: "dQw4w9WgXcQ", lang: "en us" }],
    [{ url: "dQw4w9WgXcQ", lang: "../etc" }],
    [{ url: "dQw4w9WgXcQ", extra: true }],
  ])("rejects %j", (body) => {
    expect(YoutubeIngestBodySchema.safeParse(body).success).toBe(false);
  });
});
