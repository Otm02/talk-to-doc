import { expect, test, type Page } from "@playwright/test";

const ND = "application/x-ndjson; charset=utf-8";
const lines = (...l: unknown[]) => l.map((x) => JSON.stringify(x)).join("\n") + "\n";

const meta = (over: Record<string, unknown> = {}) => ({
  documentId: "doc-1",
  title: "Me at the zoo",
  sourceType: "youtube",
  videoId: "jNQXAC9IVRw",
  // Served from the app itself so the test needs no network.
  thumbnailUrl: "/favicon.ico",
  channel: "jawed",
  durationSec: 19,
  language: "en",
  isAutoGenerated: false,
  provider: "direct",
  cached: false,
  ...over,
});

async function mockIngest(page: Page, body: string, status = 200, contentType = ND) {
  await page.route("**/api/ingest/youtube", (route) =>
    route.fulfill({ status, contentType, body }),
  );
}

test.describe("YouTube ingestion (route mocked)", () => {
  test("happy path with captions badge and timestamp links", async ({ page }) => {
    await mockIngest(
      page,
      lines(
        meta({ isAutoGenerated: true }),
        { segment: { startSec: 0, text: "All right, so here we are" } },
        { segment: { startSec: 310, text: "in front of the elephants" } },
        { done: true, stats: { segments: 2, words: 10, tokens: 14 }, coverage: 0.64 },
      ),
    );
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("https://youtu.be/jNQXAC9IVRw");
    await page.getByLabel("YouTube link").press("Enter");

    await expect(page.getByRole("heading", { name: "Me at the zoo" })).toBeVisible();
    await expect(page.getByText("Auto-generated captions")).toBeVisible();
    await expect(page.getByText("First 64% fits in the voice context")).toBeVisible();
    await expect(page.getByText(/19 s · 10 words · 14 tokens/)).toBeVisible();

    await page.getByRole("button", { name: "Show full text" }).click();
    const link = page.getByRole("link", { name: "Open at 05:10 on YouTube" });
    await expect(link).toHaveAttribute("href", "https://www.youtube.com/watch?v=jNQXAC9IVRw&t=310s");
    await expect(page.getByRole("dialog").getByText("05:00 – 10:00")).toBeVisible();
  });

  test("sample video chip loads the known-good video", async ({ page }) => {
    let sent: unknown;
    await page.route("**/api/ingest/youtube", async (route) => {
      sent = route.request().postDataJSON();
      await route.fulfill({
        status: 200,
        contentType: ND,
        body: lines(meta(), { segment: { startSec: 0, text: "hi" } }, {
          done: true,
          stats: { segments: 1, words: 1, tokens: 1 },
          coverage: 1,
        }),
      });
    });
    await page.goto("/");
    await page.getByRole("button", { name: "Sample video" }).click();
    await expect(page.getByText("Whole document in context")).toBeVisible();
    expect(sent).toMatchObject({ url: "https://www.youtube.com/watch?v=jNQXAC9IVRw" });
  });

  test("an invalid link shows an inline error and sends nothing", async ({ page }) => {
    const calls: string[] = [];
    page.on("request", (r) => r.url().includes("/api/ingest") && calls.push(r.url()));
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("https://example.com/video");
    await expect(page.getByText("That doesn't look like a YouTube video link.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Load video" })).toBeDisabled();
    await page.getByLabel("YouTube link").press("Enter");
    expect(calls).toEqual([]);
  });

  test("a playlist link explains itself", async ({ page }) => {
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("https://www.youtube.com/playlist?list=PLabc");
    await expect(page.getByText("That link is a playlist or channel.")).toBeVisible();
  });

  test("blocked YouTube offers a PDF instead", async ({ page }) => {
    await mockIngest(
      page,
      JSON.stringify({
        error: { code: "youtube_blocked", message: "x" },
        requestId: "r",
      }),
      503,
      "application/json",
    );
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("jNQXAC9IVRw");
    await page.getByLabel("YouTube link").press("Enter");
    await expect(page.locator("[role=alert]:not(#__next-route-announcer__)")).toContainText("YouTube is blocking our server");
    await page.getByRole("button", { name: "Try a PDF instead" }).click();
    await expect(page.getByLabel(/Choose a PDF/)).toBeAttached();
  });

  test("a failure can be retried", async ({ page }) => {
    let n = 0;
    await page.route("**/api/ingest/youtube", (route) => {
      n += 1;
      return n === 1
        ? route.fulfill({
            status: 502,
            contentType: "application/json",
            body: JSON.stringify({ error: { code: "youtube_failed", message: "x" } }),
          })
        : route.fulfill({
            status: 200,
            contentType: ND,
            body: lines(meta(), { segment: { startSec: 0, text: "hi" } }, {
              done: true,
              stats: { segments: 1, words: 1, tokens: 1 },
              coverage: 1,
            }),
          });
    });
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("jNQXAC9IVRw");
    await page.getByLabel("YouTube link").press("Enter");
    await page.getByRole("button", { name: "Try again" }).click();
    await expect(page.getByRole("heading", { name: "Me at the zoo" })).toBeVisible();
  });

  test("a stream cut before `done` shows a retryable error", async ({ page }) => {
    await mockIngest(page, lines(meta(), { segment: { startSec: 0, text: "hi" } }));
    await page.goto("/");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill("jNQXAC9IVRw");
    await page.getByLabel("YouTube link").press("Enter");
    await expect(page.locator("[role=alert]:not(#__next-route-announcer__)")).toContainText("We couldn't load this video's captions");
  });
});
