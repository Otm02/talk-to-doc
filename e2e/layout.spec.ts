import AxeBuilder from "@axe-core/playwright";
import { expect, test, type Page } from "@playwright/test";

// The polish gate: every screen and state, at three phone sizes, has no
// serious accessibility problem (axe, WCAG 2.1 A and AA, which includes text
// contrast), never scrolls sideways, and has no tap target under 44 px.
// Everything runs on the mock transport and a stubbed ingest route.

const SIZES = [
  { width: 390, height: 844 },
  { width: 360, height: 780 },
  { width: 430, height: 932 },
] as const;

const LONG_WORD = "Pneumonoultramicroscopicsilicovolcanoconiosis".repeat(3);
const TITLE = `Annual report 2025 ${LONG_WORD}`;

function ndjson(lines: unknown[]): string {
  return lines.map((l) => JSON.stringify(l)).join("\n") + "\n";
}

async function stubIngest(page: Page, coverage: number) {
  await page.route("**/api/ingest/pdf", (route) =>
    route.fulfill({
      status: 200,
      contentType: "application/x-ndjson",
      body: ndjson([
        { documentId: "e2e-doc", title: TITLE, sourceType: "pdf", pages: 4 },
        {
          page: 1,
          text: `Contents. ${LONG_WORD} https://example.com/${"a".repeat(120)}`,
        },
        { page: 2, text: "Revenue grew twelve percent last year." },
        { page: 3, text: "Outlook: growth is expected to continue." },
        { page: 4, text: "" },
        { done: true, stats: { pages: 4, words: 20, tokens: 30 }, coverage },
      ]),
    }),
  );
}

async function stubVideo(page: Page) {
  await page.route("**/api/ingest/youtube", (route) =>
    route.fulfill({
      status: 200,
      contentType: "application/x-ndjson",
      body: ndjson([
        {
          documentId: "e2e-video",
          title: `A talk ${LONG_WORD}`,
          sourceType: "youtube",
          videoId: "jNQXAC9IVRw",
          // Served from the app itself so the test needs no network.
          thumbnailUrl: "/favicon.ico",
          channel: "A channel",
          durationSec: 640,
          language: "en",
          isAutoGenerated: true,
          provider: "direct",
          cached: false,
        },
        { segment: { startSec: 0, text: "All right, so here we are." } },
        { segment: { startSec: 310, text: `In front of the ${LONG_WORD}.` } },
        {
          done: true,
          stats: { segments: 2, words: 12, tokens: 16 },
          coverage: 0.64,
        },
      ]),
    }),
  );
}

async function stubMic(page: Page) {
  await page.addInitScript(() => {
    const w = window as Window & { __mic?: string };
    w.__mic = new URLSearchParams(location.search).get("e2eMic") ?? "ok";
    if (typeof MediaDevices === "undefined") return;
    MediaDevices.prototype.getUserMedia = async () => {
      if (w.__mic === "denied") throw new DOMException("no", "NotAllowedError");
      return new AudioContext().createMediaStreamDestination().stream;
    };
    Object.defineProperty(navigator, "permissions", {
      configurable: true,
      value: {
        query: async () => ({
          state: w.__mic === "denied" ? "denied" : "granted",
        }),
      },
    });
  });
}

interface Problem {
  state: string;
  what: string;
}

/** Runs the three checks on whatever is on screen and files what it finds. */
async function check(page: Page, state: string, problems: Problem[]) {
  // Let entry animations finish: axe reads colours mid-fade otherwise.
  await page.waitForTimeout(350);

  const axe = await new AxeBuilder({ page })
    .withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"])
    .analyze();
  for (const v of axe.violations) {
    if (v.impact !== "serious" && v.impact !== "critical") continue;
    for (const node of v.nodes) {
      problems.push({
        state,
        what: `axe ${v.id} (${v.impact}): ${node.target.join(" ")} :: ${node.failureSummary?.split("\n")[1]?.trim() ?? ""}`,
      });
    }
  }

  const layout = await page.evaluate(() => {
    const out: string[] = [];
    const doc = document.documentElement;
    if (doc.scrollWidth > doc.clientWidth) {
      out.push(
        `page scrolls sideways: ${doc.scrollWidth} > ${doc.clientWidth}`,
      );
    }
    const describe = (el: Element) =>
      `${el.tagName.toLowerCase()}[${el.getAttribute("aria-label") ?? el.textContent?.trim().slice(0, 30) ?? ""}]`;
    const visible = (el: Element) => {
      const r = el.getBoundingClientRect();
      const s = getComputedStyle(el);
      return (
        r.width > 0 &&
        r.height > 0 &&
        s.visibility !== "hidden" &&
        s.display !== "none"
      );
    };
    // A modal sheet makes everything behind it inert: only the top layer counts.
    const dialogs = [...document.querySelectorAll('[role="dialog"]')].filter(
      visible,
    );
    const scope = dialogs.at(-1) ?? document.body;

    for (const el of scope.querySelectorAll("*")) {
      if (!visible(el)) continue;
      const r = el.getBoundingClientRect();
      // Anything sticking out past the right edge would be cut off.
      if (
        r.right > window.innerWidth + 1 &&
        !el.closest('[class*="sr-only"]')
      ) {
        out.push(
          `overflows right edge by ${Math.round(r.right - window.innerWidth)}px: ${describe(el)}`,
        );
      }
    }
    const targets = scope.querySelectorAll(
      'button, a[href], input:not([type="hidden"]):not([type="file"]), [role="radio"], [role="tab"], summary',
    );
    for (const el of targets) {
      if (!visible(el)) continue;
      // Inline references inside a sentence: see bubble.tsx for why not 44.
      if (el.matches('[data-testid="ref-chip"]')) continue;
      const r = el.getBoundingClientRect();
      if (r.width < 44 - 0.5 || r.height < 44 - 0.5) {
        out.push(
          `tap target ${Math.round(r.width)}x${Math.round(r.height)}: ${describe(el)}`,
        );
      }
    }
    return [...new Set(out)];
  });
  for (const what of layout) problems.push({ state, what });
}

const pill = (page: Page) => page.getByTestId("status-pill");

async function openDoc(page: Page, query: string) {
  await page.goto(`/?${query}`);
  await page.getByRole("button", { name: "Sample PDF" }).click();
  await expect(
    page.getByRole("button", { name: "Start voice chat" }),
  ).toBeEnabled();
}

const RUNS = [
  ...SIZES.map((size) => ({ size, scheme: "light" as const })),
  // Dark mode has its own colour tokens, so contrast is checked there too.
  { size: SIZES[0], scheme: "dark" as const },
];

for (const { size, scheme } of RUNS) {
  test.describe(`${size.width}x${size.height} ${scheme}`, () => {
    test.use({ viewport: size, colorScheme: scheme });

    test("ingest screens", async ({ page }) => {
      const problems: Problem[] = [];
      await page.goto("/");
      await expect(
        page.getByRole("heading", { name: "Talk to a document" }),
      ).toBeVisible();
      await check(page, "empty, PDF tab", problems);

      await page.getByRole("radio", { name: "YouTube" }).click();
      await check(page, "empty, YouTube tab", problems);
      await page.getByRole("radio", { name: "PDF" }).click();

      // A 429 on ingest: the same countdown as the voice screen.
      await page.route("**/api/ingest/pdf", (route) =>
        route.fulfill({
          status: 429,
          contentType: "application/json",
          headers: { "retry-after": "72" },
          body: JSON.stringify({
            error: { code: "rate_limited", message: "x", retryAfterSec: 72 },
            requestId: "r",
          }),
        }),
      );
      await page.getByRole("button", { name: "Sample PDF" }).click();
      await expect(page.getByTestId("retry-button")).toHaveText(
        /Try again in 1m \d+s/,
      );
      await check(page, "ingest error with countdown", problems);

      await page.unroute("**/api/ingest/pdf");
      await stubIngest(page, 1);
      await page.reload();
      await page.getByRole("button", { name: "Sample PDF" }).click();
      await expect(page.getByText("Whole document in context")).toBeVisible();
      await check(page, "ready, full coverage", problems);

      await page.getByRole("button", { name: "Show full text" }).click();
      await expect(
        page.getByRole("dialog", { name: "Full text" }),
      ).toBeVisible();
      await check(page, "full text sheet", problems);
      await page.getByRole("button", { name: "Close full text" }).click();

      await page.unroute("**/api/ingest/pdf");
      await stubIngest(page, 0.42);
      await page.reload();
      await page.getByRole("button", { name: "Sample PDF" }).click();
      await expect(
        page.getByText("First 42% fits in the voice context"),
      ).toBeVisible();
      await check(page, "ready, partial coverage", problems);

      await stubVideo(page);
      await page.reload();
      await page.getByRole("radio", { name: "YouTube" }).click();
      await page
        .getByLabel("YouTube link")
        .fill("https://youtu.be/jNQXAC9IVRw");
      await page.getByLabel("YouTube link").press("Enter");
      await expect(page.getByText("Auto-generated captions")).toBeVisible();
      await check(page, "ready, video", problems);
      await page.getByRole("button", { name: "Show full text" }).click();
      await expect(
        page.getByRole("link", { name: "Open at 05:10 on YouTube" }),
      ).toBeVisible();
      await check(page, "full text sheet, video", problems);

      expect(problems).toEqual([]);
    });

    test("voice chat states", async ({ page }) => {
      const problems: Problem[] = [];
      await stubMic(page);
      await stubIngest(page, 1);

      await openDoc(page, "mockRealtime=grounding");
      await page.getByRole("button", { name: "Start voice chat" }).click();
      await expect(
        page
          .locator('[data-testid="item-assistant"][data-status="done"]')
          .first(),
      ).toBeVisible({ timeout: 20_000 });
      await expect(pill(page)).toHaveText("Listening", { timeout: 10_000 });
      await check(page, "voice, listening, with chips", problems);

      await page.getByRole("button", { name: "Mute" }).click();
      await check(page, "voice, muted", problems);
      await page.getByRole("button", { name: "Unmute" }).click();

      await page.getByRole("button", { name: "Keyboard" }).click();
      await expect(page.getByTestId("composer")).toBeVisible();
      await check(page, "compact, composer open", problems);

      await page.getByRole("button", { name: "More" }).click();
      await expect(page.getByTestId("session-menu")).toBeVisible();
      await check(page, "overflow menu", problems);
      await page.getByRole("button", { name: "Close menu" }).click();

      await page
        .getByTestId("composer-row")
        .getByRole("button", { name: "End", exact: true })
        .click();
      await expect(
        page.getByRole("button", { name: "End chat" }),
      ).toBeVisible();
      await check(page, "end confirmation", problems);
      await page.getByRole("button", { name: "End chat" }).click();
      await expect(page.getByTestId("ended-panel")).toBeVisible();
      await check(page, "ended, with export", problems);

      expect(problems).toEqual([]);
    });

    test("text mode, the mic coach and the failure states", async ({
      page,
    }) => {
      const problems: Problem[] = [];
      await stubMic(page);
      await stubIngest(page, 1);

      await openDoc(page, "mockRealtime=text-turn&e2eMic=denied");
      await page.getByRole("button", { name: "Start voice chat" }).click();
      await expect(page.getByTestId("mic-banner")).toBeVisible({
        timeout: 10_000,
      });
      await page.getByRole("button", { name: "Try microphone again" }).click();
      await expect(page.getByTestId("mic-coach")).toBeVisible();
      await check(page, "text mode, mic coach open", problems);

      const composer = page.getByTestId("composer");
      await composer.fill(`What about ${LONG_WORD}?`);
      await composer.press("Enter");
      await expect(page.getByTestId("item-assistant").first()).toHaveAttribute(
        "data-status",
        "done",
        { timeout: 10_000 },
      );
      await check(page, "text mode, with a long word", problems);

      for (const [code, label] of [
        ["rate_limited", "Cooldown"],
        ["daily_limit", "Daily limit reached"],
        ["budget_exhausted", "Unavailable"],
        ["session_connect_failed", "Not connected"],
        ["session_network_failed", "Offline"],
      ] as const) {
        await openDoc(
          page,
          `mockRealtime=normal-turn&mockMintError=${code}&mockRetryAfter=72`,
        );
        await page.getByRole("button", { name: "Start voice chat" }).click();
        await expect(pill(page)).toHaveText(label, { timeout: 10_000 });
        await check(page, `failed: ${label}`, problems);
      }

      expect(problems).toEqual([]);
    });
  });
}
