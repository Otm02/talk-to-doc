import path from "node:path";
import { expect, test } from "@playwright/test";
import {
  answers,
  ndjson,
  pill,
  readDownload,
  showKeyboard,
  stubMic,
  users,
} from "./support";

// The reviewer's script, walked the way a reviewer walks it: one session per
// test, no stops in between, at 390x844. The other specs prove each piece on
// its own (docs/SPEC.md section 2.6 maps every step to its test); these prove
// that the pieces still hold when one follows the other. The voice is the mock
// transport (the build sets NEXT_PUBLIC_REALTIME_TRANSPORT=mock), so nothing
// here reaches OpenAI.

const VIDEO_ID = "jNQXAC9IVRw";

test.describe("the review script, start to finish", () => {
  test("RS-1 to RS-3 on a YouTube link: load it, talk, interrupt, follow up on the keyboard, export", async ({
    page,
  }) => {
    await stubMic(page, "ok");
    // The route is mocked, as in CI no test may reach YouTube or Supadata.
    await page.route("**/api/ingest/youtube", (route) =>
      route.fulfill({
        status: 200,
        contentType: "application/x-ndjson; charset=utf-8",
        body: ndjson(
          {
            documentId: "e2e-video",
            title: "Me at the zoo",
            sourceType: "youtube",
            videoId: VIDEO_ID,
            thumbnailUrl: "/favicon.ico",
            channel: "jawed",
            durationSec: 19,
            language: "en",
            isAutoGenerated: false,
            provider: "direct",
            cached: false,
          },
          { segment: { startSec: 0, text: "All right, so here we are" } },
          { segment: { startSec: 5, text: "in front of the elephants" } },
          {
            done: true,
            stats: { segments: 2, words: 10, tokens: 14 },
            coverage: 1,
          },
        ),
      }),
    );

    // RS-1: paste a captioned link, the transcript loads with timestamps.
    await page.goto("/?mockRealtime=barge-in");
    await page.getByRole("radio", { name: "YouTube" }).click();
    await page.getByLabel("YouTube link").fill(`https://youtu.be/${VIDEO_ID}`);
    await page.getByLabel("YouTube link").press("Enter");
    await expect(
      page.getByRole("heading", { name: "Me at the zoo" }),
    ).toBeVisible();
    await page.getByRole("button", { name: "Show full text" }).click();
    await expect(
      page.getByRole("link", { name: "Open at 00:05 on YouTube" }),
    ).toHaveAttribute(
      "href",
      `https://www.youtube.com/watch?v=${VIDEO_ID}&t=5s`,
    );
    await page.getByRole("button", { name: "Close full text" }).click();

    // RS-3: start a voice chat and interrupt the assistant.
    await page.getByRole("button", { name: "Start voice chat" }).click();
    await expect(answers(page).first()).toHaveAttribute(
      "data-status",
      "interrupted",
      { timeout: 15_000 },
    );
    await expect(page.getByTestId("interrupted-marker")).toBeVisible();
    // The natural follow-up arrives by voice and is answered in the same chat.
    await expect(users(page).nth(1)).toContainText("Just the margins.", {
      timeout: 15_000,
    });
    await expect(answers(page).nth(1)).toHaveAttribute("data-status", "done", {
      timeout: 15_000,
    });

    // Then a typed follow-up, with the soft keyboard up (390x420).
    await page.getByRole("button", { name: "Keyboard" }).click();
    await showKeyboard(page);
    const composer = page.getByTestId("composer");
    await expect(composer).toBeFocused();
    await composer.fill("And the outlook?");
    await composer.press("Enter");
    await expect(users(page).nth(2)).toContainText("And the outlook?");
    await expect(answers(page).nth(2)).toHaveAttribute("data-status", "done", {
      timeout: 15_000,
    });
    const sizes = await page.evaluate(() => {
      const h = (id: string) =>
        document.querySelector(`[data-testid="${id}"]`)?.getBoundingClientRect()
          .height ?? 0;
      return {
        transcript: h("transcript-region"),
        visible: window.visualViewport?.height ?? window.innerHeight,
      };
    });
    expect(sizes.transcript / sizes.visible).toBeGreaterThanOrEqual(0.7);

    // The Markdown export names the video's URL and keeps the order.
    await page.getByRole("button", { name: "More" }).click();
    const [download] = await Promise.all([
      page.waitForEvent("download"),
      page.getByRole("button", { name: "Download transcript" }).click(),
    ]);
    expect(download.suggestedFilename()).toMatch(
      /^me-at-the-zoo-\d{4}-\d{2}-\d{2}\.md$/,
    );
    const md = await readDownload(download);
    expect(md).toContain("# Me at the zoo\n");
    expect(md).toContain(
      `- Source: https://www.youtube.com/watch?v=${VIDEO_ID}`,
    );
    expect(md).toMatch(/\*\*Assistant:\*\* .+ \*\(interrupted\)\*/);
    const order = [
      "**You:** Summarise this report.",
      "**You:** Just the margins.",
      "**You:** And the outlook?",
    ].map((s) => md.indexOf(s));
    expect(order.every((i) => i >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  test("RS-2 on a real PDF: the real route reads it, the chat names a page, the chip opens it, export", async ({
    page,
  }) => {
    await stubMic(page, "ok");
    await page.goto("/?mockRealtime=grounding");

    // The real route, in direct mode: a 4-page file through the multipart path.
    await page
      .getByLabel(/Choose a PDF/)
      .setInputFiles(
        path.join(process.cwd(), "test/fixtures/pdf/multi-page.pdf"),
      );
    await expect(page.getByText(/4 pages · [\d,]+ words/)).toBeVisible();
    await page.getByRole("button", { name: "Show full text" }).click();
    const sheet = page.getByRole("dialog", { name: "Full text" });
    await expect(sheet.getByRole("region", { name: "Page 4" })).toBeAttached();
    await page.getByRole("button", { name: "Close full text" }).click();

    await page.getByRole("button", { name: "Start voice chat" }).click();
    await expect(answers(page).first()).toHaveAttribute("data-status", "done", {
      timeout: 20_000,
    });

    // Pages 2 and 3-4 are in this file; "Page 40" is not, so it stays text.
    const chips = answers(page).first().getByTestId("ref-chip");
    await expect(chips).toHaveText(["page 2", "pages 3 to 4"]);
    await chips.nth(1).click();
    const page3 = sheet.getByRole("region", { name: "Page 3" });
    await expect(page3).toBeInViewport();
    await expect(page3).toHaveAttribute("data-highlight", "true");
    await page.getByRole("button", { name: "Close full text" }).click();

    await page.getByRole("button", { name: "More" }).click();
    const [download] = await Promise.all([
      page.waitForEvent("download"),
      page.getByRole("button", { name: "Download transcript" }).click(),
    ]);
    const md = await readDownload(download);
    expect(md).toContain("# Quarterly Report 2026\n");
    expect(md).toContain("- Source: multi-page.pdf\n");
    expect(md).toContain("**You:** Where is revenue covered?");
    await expect(pill(page)).toBeVisible();
  });
});
